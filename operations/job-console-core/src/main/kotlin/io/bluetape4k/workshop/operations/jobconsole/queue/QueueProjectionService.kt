package io.bluetape4k.workshop.operations.jobconsole.queue

import io.bluetape4k.support.requireZeroOrPositiveNumber
import io.bluetape4k.workshop.operations.jobconsole.api.EtaConfidence
import io.bluetape4k.workshop.operations.jobconsole.api.JobType
import io.bluetape4k.workshop.operations.jobconsole.api.QueueProjection
import io.bluetape4k.workshop.operations.jobconsole.domain.JobState
import java.nio.ByteBuffer
import java.time.Instant
import java.util.*
/**
 * QueueRow은 운영 작업 콘솔에서 전달되는 불변 데이터 모델입니다.
 * @property jobId 업무 객체의 불변 식별자입니다. API·영속화·이벤트가 같은 대상을 가리키도록 생성 후 변경하지 않습니다.
 * @property jobType 운영 작업 콘솔 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property state 현재 운영 작업 콘솔 처리의 분류 또는 수명주기 값입니다. 허용된 전이·재시도·오류 응답을 선택하는 기준이며 임의의 문자열로 해석하지 않습니다.
 * @property enqueueSequence 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 * @property queueVersion 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 * @property updatedAt 운영 작업 콘솔의 업무 시각입니다. 만료·정렬·재시도·SLA 판정에 사용하므로 저장소와 API에서 동일한 시간대와 clock 정책을
 * 유지합니다.
 */


data class QueueRow(
    /**
     * `jobId`은 작업 운영 콘솔에서 업무 대상의 불변 식별자입니다.
     *
     * 생성 후 변경하지 않으며 API·영속화·이벤트가 같은 대상을 가리키도록 유지합니다.
     */
    val jobId: UUID,
    /**
     * `jobType`은 작업 운영 콘솔에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
     *
     * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
     */
    val jobType: JobType,
    /**
     * `state`은 작업 운영 콘솔에서 허용된 상태 전이와 terminal 여부를 선택하는 생명주기 값입니다.
     *
     * 임의 문자열로 해석하지 말고 전이표·재시도·보상 규칙을 함께 적용합니다.
     */
    val state: JobState,
    /**
     * `enqueueSequence`은 작업 운영 콘솔에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val enqueueSequence: Long,
    /**
     * `queueVersion`은 작업 운영 콘솔에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val queueVersion: Long,
    /**
     * `updatedAt`은 작업 운영 콘솔에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val updatedAt: Instant,
)
/**
 * QueuePage은 운영 작업 콘솔에서 전달되는 불변 데이터 모델입니다.
 * @property items 운영 작업 콘솔 경계에서 전달되는 업무 내용입니다. 스키마·크기·무결성을 검증한 뒤 저장·발행하며 후속 상태 전이에 필요한 정보만 포함합니다.
 * @property nextCursor 운영 작업 콘솔 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


data class QueuePage(
    /**
     * `items`은 작업 운영 콘솔에서 업무 집합 또는 조회 결과입니다.
     *
     * 빈 집합·중복·정렬·페이지 경계를 정의하고 기준 저장소의 순서를 그대로 보존합니다.
     */
    val items: List<QueueRow>,
    /**
     * `nextCursor`은 작업 운영 콘솔에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val nextCursor: String?,
)

/**
 * QueueProjectionService은 운영 작업 콘솔 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
 * 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
object QueueProjectionService {
    /**
     * `DEFAULT_PAGE_SIZE`은 작업 운영 콘솔에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
     *
     * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
     */
    const val DEFAULT_PAGE_SIZE: Int = 25
    /**
     * `MAX_PAGE_SIZE`은 작업 운영 콘솔에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
     *
     * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
     */
    const val MAX_PAGE_SIZE: Int = 100

    /**
     * project은 운영 작업 콘솔의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param rows 업무 처리에 필요한 rows 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param targetJobId 처리할 운영 작업 콘솔 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    fun project(rows: List<QueueRow>, targetJobId: UUID, now: Instant): QueueProjection {
        /**
         * 운영 작업 콘솔 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val active = rows.filterNot { it.state.terminal }.sortedBy { it.enqueueSequence }
        /**
         * 운영 작업 콘솔 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val targetIndex = active.indexOfFirst { it.jobId == targetJobId }
        targetIndex.requireZeroOrPositiveNumber { "target job is not in the active tenant queue" }
        /**
         * 운영 작업 콘솔 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */

        val target = active[targetIndex]
        return QueueProjection(
            position = targetIndex + 1,
            jobsAhead = targetIndex,
            estimatedStartRange = null,
            estimatedCompletionRange = null,
            confidence = EtaConfidence.INSUFFICIENT_DATA,
            sampleSize = 0,
            queueVersion = target.queueVersion,
            updatedAt = now,
        )
    }

    /**
     * page은 운영 작업 콘솔의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param rows 업무 처리에 필요한 rows 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param cursor 업무 처리에 필요한 cursor 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param requestedSize 운영 작업 콘솔 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     */
    fun page(rows: List<QueueRow>, cursor: String?, requestedSize: Int): QueuePage {
        val size = requestedSize.coerceIn(1, MAX_PAGE_SIZE)
        val after = cursorSequence(cursor)
        val candidates = rows.asSequence()
            .filter { after == null || it.enqueueSequence > after }
            .sortedBy { it.enqueueSequence }
            .toList()
        val items = candidates.take(size)
        val next = if (candidates.size > size) encodeCursor(items.last().enqueueSequence) else null
        return QueuePage(items, next)
    }

    /**
     * cursorSequence은 운영 작업 콘솔의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param cursor 업무 처리에 필요한 cursor 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    fun cursorSequence(cursor: String?): Long? = cursor?.let(::decodeCursor)

    /**
     * encodeCursor은 운영 작업 콘솔 경계의 payload를 계약된 스키마와 canonical 표현으로 변환하고, 누락·버전 불일치·무결성 오류를 업무 오류로
     * 분류합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param sequence 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
     */
    private fun encodeCursor(sequence: Long): String =
        Base64.getUrlEncoder().withoutPadding()
            .encodeToString(ByteBuffer.allocate(Long.SIZE_BYTES).putLong(sequence).array())

    /**
     * decodeCursor은 운영 작업 콘솔 경계의 payload를 계약된 스키마와 canonical 표현으로 변환하고, 누락·버전 불일치·무결성 오류를 업무 오류로
     * 분류합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param cursor 업무 처리에 필요한 cursor 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun decodeCursor(cursor: String): Long =
        runCatching {
            ByteBuffer.wrap(Base64.getUrlDecoder().decode(cursor)).long
        }.getOrElse {
            throw IllegalArgumentException("invalid queue cursor")
        }
}
