 */
object JobRequestTable: Table("job_requests") {
    /**
     * 운영 작업 콘솔 요청이 속한 테넌트 식별자입니다. 저장·이벤트·멱등성 범위를 이 값으로 분리합니다.
     */
    val tenantId = varchar("tenant_id", 64)
    /**
     * 호출 주체 참조값입니다. 권한·중복 요청·감사 추적에 사용하며 원문 개인정보는 노출하지 않습니다.
     */
    val submitterHash = char("submitter_hash", 64)
    /**
     * 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
     */
    val keyHash = char("key_hash", 64)
    /**
     * 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
     */
    val requestFingerprint = char("request_fingerprint", 64)
    /**
     * `jobId`은 작업 운영 콘솔에서 업무 대상의 불변 식별자입니다.
     *
     * 생성 후 변경하지 않으며 API·영속화·이벤트가 같은 대상을 가리키도록 유지합니다.
     */
