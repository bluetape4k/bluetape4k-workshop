/** mutation과 immutable evidence가 transaction 하나를 공유하는 fenced operator request입니다. */
/** mutation과 immutable evidence가 transaction 하나를 공유하는 fenced operator request입니다. */
@ConsistentCopyVisibility
internal data class RebuildCancellationCommand private constructor(
    /**
     * `identity`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val identity: OperatorAuditIdentity,
    /**
     * `target`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val target: OperatorAuditTarget,
    /**
     * `checkpointPosition`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val checkpointPosition: Long,
    /**
     * `streamPosition`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val streamPosition: Long,
    /**
     * `occurredAt`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val occurredAt: Instant,
): Serializable {
    /**
     * 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
     */

    val key: ProjectionKey get() = ProjectionKey(target.projection, target.generation)

    companion object {
        /**
         * `serialVersionUID`은 바우처·프로모션에서 Java 직렬화 호환성을 유지하는 기술 메타데이터입니다.
         *
         * 도메인 상태가 아니므로 값을 바꾸거나 업무 식별자로 사용하지 않습니다.
         */
        private const val serialVersionUID: Long = 1L

        /**
         * invoke은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param identity 업무 처리에 필요한 identity 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         * @param target 업무 처리에 필요한 target 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         * @param checkpointPosition 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
         * @param streamPosition 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
         * @param occurredAt 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
         */
        operator fun invoke(
            identity: OperatorAuditIdentity,
            target: OperatorAuditTarget,
            checkpointPosition: Long,
            streamPosition: Long,
            occurredAt: Instant,
        ): RebuildCancellationCommand {
            val validCheckpoint = checkpointPosition.requireZeroOrPositiveNumber("checkpointPosition")
            val validStreamPosition = streamPosition.requireZeroOrPositiveNumber("streamPosition")

            return RebuildCancellationCommand(
                identity = identity,
                target = target,
                checkpointPosition = validCheckpoint,
                streamPosition = validStreamPosition,
                occurredAt = occurredAt,
            )
        }
    }
}
/**
 * RebuildCancellationOutcome은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property state 현재 프로모션 바우처 처리의 분류 또는 수명주기 값입니다. 허용된 전이·재시도·오류 응답을 선택하는 기준이며 임의의 문자열로 해석하지 않습니다.
 * @property audit 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


internal data class RebuildCancellationOutcome(
    /**
     * `state`은 바우처·프로모션에서 허용된 상태 전이와 terminal 여부를 선택하는 생명주기 값입니다.
     *
     * 임의 문자열로 해석하지 말고 전이표·재시도·보상 규칙을 함께 적용합니다.
     */
    val state: ProjectionGenerationState,
    /**
     * `audit`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val audit: OperatorAuditEntry,
)

/**
 * rebuild cancellation, fencing verification, operator evidence를 분리할 수 없게 유지합니다.
 * generic mutation API를 의도적으로 노출하지 않습니다. caller는 같은 foreground database transaction에서
 * 일치하는 audit record를 쓰지 않으면 rebuild state를 advance할 수 없습니다.
 * @property transactions 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property rebuilds 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property audits 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class EventSourcedRebuildOperator(
    /**
     * `transactions`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val transactions: EventSourcedPermitTransactionRunner,
    /**
     * `rebuilds`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val rebuilds: ProjectionRebuildRepository,
    /**
     * `audits`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val audits: OperatorAuditRepository,
) {

    private companion object: KLogging() {
        /**
         * 프로모션 바우처의 상태·분류·오류 코드를 나타냅니다. 허용된 전이와 재시도·응답 분기를 선택하는 기준입니다.
         */
        private const val REJECTED_REASON = "REBUILD_NOT_CANCELLABLE"
        /**
         * 프로모션 바우처의 상태·분류·오류 코드를 나타냅니다. 허용된 전이와 재시도·응답 분기를 선택하는 기준입니다.
         */
        private val CANCELLABLE_STATES = setOf(
            ProjectionGenerationState.BUILDING,
            ProjectionGenerationState.VALIDATING
        )
    }

    /**
     * cancel은 프로모션 바우처의 취소·보상·종료 전이를 허용된 terminal 규칙에 따라 적용하고, 이미 처리된 요청은 멱등하게 유지합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     */
    fun cancel(command: RebuildCancellationCommand): RebuildCancellationOutcome =
        transactions.inTransaction {
            /**
             * `before`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
             *
             * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
             */
            val before = checkNotNull(findGeneration(command.key)) { "rebuild generation does not exist" }
            /**
             * `after`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
             *
             * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
             */
            val after = cancellationResult(command, before.state, before.fencingToken)
            /**
             * `outcome`은 바우처·프로모션에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
             *
             * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
             */
            val outcome = when {
                after.fencingToken != before.fencingToken -> OperatorAuditOutcome.APPLIED
                else                                      -> OperatorAuditOutcome.REJECTED
            }

            /**
             * `audit`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
             *
             * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
             */
            val audit = OperatorAuditEntry(
                identity = command.identity,
                action = OperatorAuditAction.REBUILD_CANCELLED,
                target = command.target,
                transition =
                    OperatorAuditTransition(
                        beforeState = before.state,
                        afterState = after.state,
                        checkpointPosition = command.checkpointPosition,
                        streamPosition = command.streamPosition,
                        reasonClass = if (outcome == OperatorAuditOutcome.APPLIED) null else REJECTED_REASON,
                    ),
                result = OperatorAuditResult(outcome, command.occurredAt),
            )
            audits.append(audit)
            RebuildCancellationOutcome(after.state, audit)
        }

    /**
     * cancellationResult은 프로모션 바우처의 취소·보상·종료 전이를 허용된 terminal 규칙에 따라 적용하고, 이미 처리된 요청은 멱등하게 유지합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param beforeState 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param observedFencingToken 재전송·멱등성·무결성 확인에 사용하는 값입니다. 원문 비밀이나 개인정보를 로그에 남기지 않습니다.
     */
    private fun cancellationResult(
        command: RebuildCancellationCommand,
        beforeState: ProjectionGenerationState,
        observedFencingToken: Long,
    ): ProjectionGeneration =
        if (command.target.expectedFencingToken != observedFencingToken || beforeState !in CANCELLABLE_STATES) {
            findGeneration(command.key).checkNotNull { "rebuild generation disappeared" }
        } else {
            rebuilds.requestCancellation(command.key, command.occurredAt).checkNotNull {
                "rebuild generation disappeared during cancellation"
            }
        }
}
