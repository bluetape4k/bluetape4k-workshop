package io.bluetape4k.workshop.commerce.voucher.eventsourced.operations

import io.bluetape4k.javatimes.nanos
import io.bluetape4k.javatimes.requirePositiveDuration
import io.bluetape4k.javatimes.seconds
import io.bluetape4k.logging.KLogging
import io.bluetape4k.logging.warn
import java.time.Duration
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.locks.ReentrantLock
import kotlin.concurrent.withLock

/**
 * `EventSourcedShutdownEvent`은 업무 분기용 제한된 값 집합입니다.
 * 업무 흐름의 허용된 분기를 고정하며 저장·이벤트·API 경계에서 동일하게 해석합니다.
 */
internal enum class EventSourcedShutdownEvent {
    /**
     * `EventSourcedShutdownEvent.READINESS_DOWN`은 `readiness down` 업무 상황을 나타냅니다. 현재 aggregate의
     * revision과
     * 허용된 전이를 확인한 뒤 사용합니다.
     */
    READINESS_DOWN,
    /**
     * `EventSourcedShutdownEvent.REJECT_ADMISSION`은 `reject admission` 업무 상황을 나타냅니다. 현재 aggregate의
     * revision과 허용된 전이를 확인한 뒤 사용합니다.
     */
    REJECT_ADMISSION,
    /**
     * `EventSourcedShutdownEvent.STOP_PROJECTION`은 `stop projection` 업무 상황을 나타냅니다. 현재 aggregate의
     * revision과
     * 허용된 전이를 확인한 뒤 사용합니다.
     */
    STOP_PROJECTION,
    /**
     * `EventSourcedShutdownEvent.STOP_REBUILD`은 `stop rebuild` 업무 상황을 나타냅니다. 현재 aggregate의
     * revision과 허용된
     * 전이를 확인한 뒤 사용합니다.
     */
    STOP_REBUILD,
    /**
     * `EventSourcedShutdownEvent.STOP_MAINTENANCE`은 `stop maintenance` 업무 상황을 나타냅니다. 현재 aggregate의
     * revision과 허용된 전이를 확인한 뒤 사용합니다.
     */
    STOP_MAINTENANCE,
    /**
     * `EventSourcedShutdownEvent.AWAIT_DRAIN`은 `await drain` 업무 상황을 나타냅니다. 현재 aggregate의 revision과
     * 허용된 전이를
     * 확인한 뒤 사용합니다.
     */
    AWAIT_DRAIN,
    /**
     * `EventSourcedShutdownEvent.RELEASE_FENCED_LEASES`은 `release fenced leases` 업무 상황을 나타냅니다. 현재
     * aggregate의 revision과 허용된 전이를 확인한 뒤 사용합니다.
     */
    RELEASE_FENCED_LEASES,
}
/**
 * EventSourcedWorkerShutdown은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property projection 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property rebuild 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property maintenance 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property releaseFencedLeases 재시도·임대·보존·처리 제한을 결정하는 시간 길이입니다. 장애 시 무한 대기나 중복 실행을 막는 정책 경계입니다.
 */


internal data class EventSourcedWorkerShutdown(
    /**
     * `projection`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val projection: () -> Unit,
    /**
     * `rebuild`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val rebuild: () -> Unit,
    /**
     * `maintenance`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val maintenance: () -> Unit,
    /**
     * `releaseFencedLeases`은 바우처·프로모션에서 멱등성·무결성·lease fencing을 확인하는 보호 값입니다.
     *
     * 원문 비밀값을 로그·일반 응답에 노출하지 않고 재시도와 오래된 worker를 안전하게 차단합니다.
     */
    val releaseFencedLeases: () -> Unit,
)

/**
 * stale worker가 더 새로운 lease를 release하지 못하게 하면서 graceful shutdown을 조율합니다.
 * @property state 프로모션 바우처의 상태·분류·오류 코드를 나타냅니다. 허용된 전이와 재시도·응답 분기를 선택하는 기준입니다.
 * @property gate 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property workers 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class EventSourcedLifecycleCoordinator(
    /**
     * `state`은 바우처·프로모션에서 허용된 상태 전이와 terminal 여부를 선택하는 생명주기 값입니다.
     *
     * 임의 문자열로 해석하지 말고 전이표·재시도·보상 규칙을 함께 적용합니다.
     */
    private val state: EventSourcedOperationalState,
    /**
     * `gate`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val gate: EventSourcedDatabasePermitGate,
    /**
     * `workers`은 바우처·프로모션에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
     *
     * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
     */
    private val workers: EventSourcedWorkerShutdown,
    graceDeadline: Duration = DEFAULT_GRACE_DEADLINE,
) {
    /**
     * 프로모션 바우처의 업무 시각입니다. 만료·정렬·재시도·SLA 판정에 같은 clock 기준을 사용합니다.
     */
    private val graceDeadline = graceDeadline.requirePositiveDuration("graceDeadline")
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val shuttingDown = AtomicBoolean()
    /**
     * 프로모션 바우처 경계의 전달 데이터입니다. 스키마·크기·무결성을 검증한 뒤 저장하거나 발행합니다.
     */
    private val eventLock = ReentrantLock()
    /**
     * 프로모션 바우처 경계의 전달 데이터입니다. 스키마·크기·무결성을 검증한 뒤 저장하거나 발행합니다.
     */
    private val recordedEvents = mutableListOf<EventSourcedShutdownEvent>()
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */

    @Volatile
    private var drainForced = false

    /**
     * shutdown은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun shutdown() {
        if (!shuttingDown.compareAndSet(false, true)) return

        val deadline = System.nanoTime() + graceDeadline.toNanos()

        step(EventSourcedShutdownEvent.READINESS_DOWN, state::beginShutdown)
        step(EventSourcedShutdownEvent.REJECT_ADMISSION, gate::beginShutdown)
        step(EventSourcedShutdownEvent.STOP_PROJECTION, workers.projection)
        step(EventSourcedShutdownEvent.STOP_REBUILD, workers.rebuild)
        step(EventSourcedShutdownEvent.STOP_MAINTENANCE, workers.maintenance)
        record(EventSourcedShutdownEvent.AWAIT_DRAIN)

        if (!gate.awaitDrained(remaining(deadline))) {
            drainForced = true
            log.warn { "event_sourced_shutdown_drain_deadline_exceeded" }
        }
        step(EventSourcedShutdownEvent.RELEASE_FENCED_LEASES, workers.releaseFencedLeases)
    }

    /**
     * events은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun events(): List<EventSourcedShutdownEvent> = eventLock.withLock { recordedEvents.toList() }

    /**
     * forcedDrain은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun forcedDrain(): Boolean = drainForced

    /**
     * step은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param action 업무 처리에 필요한 action 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private inline fun step(
        event: EventSourcedShutdownEvent,
        action: () -> Unit,
    ) {
        record(event)
        action()
    }

    /**
     * record은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     */
    private fun record(event: EventSourcedShutdownEvent) {
        eventLock.withLock { recordedEvents += event }
    }

    /**
     * remaining은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param deadline 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun remaining(deadline: Long): Duration =
        (deadline - System.nanoTime()).coerceAtLeast(0).nanos()

    private companion object: KLogging() {
        /**
         * `DEFAULT_GRACE_DEADLINE`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        private val DEFAULT_GRACE_DEADLINE: Duration = 10.seconds()
    }
}
