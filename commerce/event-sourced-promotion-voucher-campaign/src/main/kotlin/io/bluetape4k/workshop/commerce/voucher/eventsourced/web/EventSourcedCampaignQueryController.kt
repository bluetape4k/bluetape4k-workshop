 * @property campaign 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property positions 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 */

    data class Fresh(
        /**
         * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val campaign: CampaignHttpResponse,
        /**
         * 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값이 다르면 오래된 명령을 거부합니다.
         */
        val positions: ProjectionPositions,
    ): CampaignProjectionResult
/**
 * Pending은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property positions 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 */


    data class Pending(
        /**
         * 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값이 다르면 오래된 명령을 거부합니다.
         */
        val positions: ProjectionPositions,
    ): CampaignProjectionResult

    /**
     * NotFound은 이벤트 소싱 프로모션 바우처 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
     * 해석합니다.
     *
     * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
     */
    data object NotFound: CampaignProjectionResult
}

/**
 * `CampaignProjectionQuery`은 이벤트 기반 프로모션 바우처 캠페인 실무 예제에서 업무 경계와 협력 계약을 표현하는 타입입니다.
 *
 * 입력 검증, 권한·멱등성 확인, 상태 전이, 저장소 확정, 이벤트 발행 사이의 책임을 이 타입의 계약으로 명확히 하여 운영자가 현재 상태와 다음 조치를 추적할 수 있게
 * 합니다.
 */
internal fun interface CampaignProjectionQuery {
    /**
     * campaign은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param request 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     */
    fun campaign(request: CampaignProjectionRequest): CampaignProjectionResult
}

/**
 * GET query adapter입니다. command는 이 projection-consistency path를 retry하거나 통과하지 않습니다.
 * @property queries 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
@RestController
@RequestMapping("/api/v1")
internal class EventSourcedCampaignQueryController(
    /**
     * `queries`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val queries: CampaignProjectionQuery,
) {
    /**
     * `campaign`은 HTTP API의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 매핑 경계: `GetMapping`. 인증 실패·검증 실패·멱등성 충돌은 성공 응답처럼 숨기지 않고 계약된 오류로 반환합니다.
     * 예:
     * ```kotlin
     * val response = campaign(campaignId = UUID.randomUUID(), tenantHeader = "tenant-a",
     * principalHeader =
     * null, minimumStreamPositionHeader = null)
     * ```
     * @param campaignId 요청 경계에서 검증된 `campaignId`입니다.
     * @param tenantHeader 요청 경계에서 검증된 `tenantHeader`입니다.
     * @param principalHeader 요청 경계에서 검증된 `principalHeader`입니다.
     * @param minimumStreamPositionHeader 요청 경계에서 검증된 `minimumStreamPositionHeader`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    @GetMapping("/campaigns/{campaignId}")
    fun campaign(
        @PathVariable campaignId: UUID,
        @RequestHeader(TENANT_HEADER, required = false) tenantHeader: String?,
        @RequestHeader(PRINCIPAL_HEADER, required = false) principalHeader: String?,
        @RequestHeader(MIN_STREAM_POSITION_HEADER, required = false) minimumStreamPositionHeader: String?,
    ): ResponseEntity<Any> {
        val tenant = tenantHeader.requireNotBlank(TENANT_HEADER)
        val principal = principalHeader.requireNotBlank(PRINCIPAL_HEADER)

        val result = queries.campaign(
            CampaignProjectionRequest(
                tenant = tenant,
                principal = principal,
                campaignId = campaignId,
                minimumStreamPosition = minimumStreamPositionHeader.toMinimumStreamPosition(),
            ),
        )
        return result.toResponse()
    }
}

/**
 * toResponse은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
 *
 * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
 */
private fun CampaignProjectionResult.toResponse(): ResponseEntity<Any> =
    when (this) {
        is CampaignProjectionResult.Fresh -> ResponseEntity.ok().headers(positions.toHeaders()).body(campaign)
        is CampaignProjectionResult.Pending ->
            ResponseEntity.accepted()
                .header(HttpHeaders.RETRY_AFTER, "1")
                .headers(positions.toHeaders())
                .body(
                    ProjectionPendingHttpResponse(
                        currentStreamPosition = positions.streamPosition,
                        projectionPosition = positions.projectionPosition,
                        lag = positions.lag,
                    ),
                )

        CampaignProjectionResult.NotFound -> ResponseEntity.notFound().build()
    }

/**
 * toHeaders은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
 *
 * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
 */
private fun ProjectionPositions.toHeaders(): HttpHeaders =
    HttpHeaders().apply {
        set(STREAM_POSITION_HEADER, streamPosition.toString())
        set(PROJECTION_POSITION_HEADER, projectionPosition.toString())
        set(PROJECTION_LAG_HEADER, lag.toString())
    }

/**
 * toMinimumStreamPosition은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된
 * 응답으로 매핑합니다.
 *
 * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
 */
private fun String?.toMinimumStreamPosition(): Long? {
    if (this == null) return null
    return toLongOrNull()
        .requireNotNull(MIN_STREAM_POSITION_HEADER)
        .requireZeroOrPositiveNumber(MIN_STREAM_POSITION_HEADER)
}
