/**
 * `CAMPAIGN_PROJECTION`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
 *
 * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
 */
private const val CAMPAIGN_PROJECTION = "voucher-lifecycle"
/**
 * `MAX_CONSISTENCY_WAIT_SECONDS`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
 *
 * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
 */
private const val MAX_CONSISTENCY_WAIT_SECONDS = 5L
/**
 * `CONSISTENCY_POLL_INTERVAL_MILLIS`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
 *
 * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
 */
private const val CONSISTENCY_POLL_INTERVAL_MILLIS = 25L
/**
 * `MAX_CONSISTENCY_WAIT`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
 *
 * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
 */
private val MAX_CONSISTENCY_WAIT: Duration = MAX_CONSISTENCY_WAIT_SECONDS.seconds()
/**
 * `CONSISTENCY_POLL_INTERVAL`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
 *
 * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
 */
private val CONSISTENCY_POLL_INTERVAL: Duration = CONSISTENCY_POLL_INTERVAL_MILLIS.millis()
/**
 * CampaignProjectionSnapshot은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property campaign 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property positions 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 */


internal data class CampaignProjectionSnapshot(
    /**
     * `campaign`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val campaign: CampaignProjectionReadModel?,
    /**
     * `positions`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val positions: ProjectionPositions,
)

/**
 * `CampaignProjectionSnapshotReader`은 이벤트 기반 프로모션 바우처 캠페인 실무 예제에서 업무 경계와 협력 계약을 표현하는 타입입니다.
 *
 * 입력 검증, 권한·멱등성 확인, 상태 전이, 저장소 확정, 이벤트 발행 사이의 책임을 이 타입의 계약으로 명확히 하여 운영자가 현재 상태와 다음 조치를 추적할 수 있게
 * 합니다.
 */
internal fun interface CampaignProjectionSnapshotReader {
    /**
     * read은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param campaignId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     */
    fun read(
        tenantId: TenantId,
        campaignId: java.util.UUID,
    ): CampaignProjectionSnapshot
}
/**
 * ExposedCampaignProjectionSnapshotReader은 프로모션 바우처에서 사용하는 업무 객체입니다.
 * @property repository 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */


internal class ExposedCampaignProjectionSnapshotReader(
    database: Database,
    permits: EventSourcedDatabasePermitGate,
    /**
     * `repository`은 바우처·프로모션에서 업무 규칙을 위임하는 저장소·외부 시스템 협력자입니다.
     *
     * 기준 데이터와 재시도·timeout 정책을 숨기지 않고 호출자가 결과를 복구할 수 있게 합니다.
     */
    private val repository: ProjectionRepository,
): CampaignProjectionSnapshotReader {
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */

    private val transactions = EventSourcedPermitTransactionRunner(
        database = database,
        permits = permits,
        lane = EventSourcedDatabaseLane.FOREGROUND
    )

    /**
     * read은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param campaignId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     */
    override fun read(
        tenantId: TenantId,
        campaignId: java.util.UUID,
    ): CampaignProjectionSnapshot =
        transactions.inTransaction {
            val active = findActive(CAMPAIGN_PROJECTION)
            val key = active?.let { ProjectionKey(it.projection, it.generation) }
            val projectionPosition = key?.let(repository::checkpoint)?.position ?: 0L
            val streamPosition = EventLog
                .selectAll()
                .orderBy(EventLog.globalPosition to SortOrder.DESC)
                .limit(1)
                .singleOrNull()
                ?.get(EventLog.globalPosition)
                ?: 0L

            CampaignProjectionSnapshot(
                campaign = key?.let { repository.campaign(it, tenantId, campaignId) },
                positions = ProjectionPositions(streamPosition, projectionPosition),
            )
        }
}

/**
 * `CampaignProjectionWaiter`은 이벤트 기반 프로모션 바우처 캠페인 실무 예제에서 업무 경계와 협력 계약을 표현하는 타입입니다.
 *
 * 입력 검증, 권한·멱등성 확인, 상태 전이, 저장소 확정, 이벤트 발행 사이의 책임을 이 타입의 계약으로 명확히 하여 운영자가 현재 상태와 다음 조치를 추적할 수 있게
 * 합니다.
 */
internal fun interface CampaignProjectionWaiter {
    /**
     * pause은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun pause(): Boolean
}
/**
 * WaitingCampaignProjectionQuery은 프로모션 바우처에서 사용하는 업무 객체입니다.
 * @property snapshots 프로모션 바우처 경계의 전달 데이터입니다. 스키마·크기·무결성을 검증한 뒤 저장하거나 발행합니다.
 * @property clock 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property nanoTime 프로모션 바우처의 업무 시각입니다. 만료·정렬·재시도·SLA 판정에 같은 clock 기준을 사용합니다.
 * @property waiter 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
 */


internal class WaitingCampaignProjectionQuery(
    /**
     * `snapshots`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val snapshots: CampaignProjectionSnapshotReader,
    /**
     * `clock`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val clock: Clock = Clock.systemUTC(),
    /**
     * `nanoTime`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val nanoTime: () -> Long = System::nanoTime,
    /**
     * `waiter`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val waiter: CampaignProjectionWaiter = PARKING_WAITER,
): CampaignProjectionQuery {
    /**
     * campaign은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param request 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     */
    override fun campaign(request: CampaignProjectionRequest): CampaignProjectionResult {
        val startedAt = nanoTime()
        var snapshot = snapshots.read(TenantId(request.tenant), request.campaignId)
        while (snapshot.isBefore(request.minimumStreamPosition) && withinDeadline(startedAt) && waiter.pause()) {
            snapshot = snapshots.read(TenantId(request.tenant), request.campaignId)
        }
        return snapshot.toResult(request.minimumStreamPosition)
    }

    /**
     * withinDeadline은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로
     * 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param startedAt 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun withinDeadline(startedAt: Long): Boolean =
        nanoTime() - startedAt < MAX_CONSISTENCY_WAIT.toNanos()

    /**
     * toResult은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param minimumPosition 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
     */
    private fun CampaignProjectionSnapshot.toResult(minimumPosition: Long?): CampaignProjectionResult =
        when {
            isBefore(minimumPosition) -> CampaignProjectionResult.Pending(positions)
            campaign == null -> CampaignProjectionResult.NotFound
            else             -> CampaignProjectionResult.Fresh(campaign.toHttp(clock), positions)
        }

    private companion object {
        /**
         * `PARKING_WAITER`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val PARKING_WAITER = CampaignProjectionWaiter {
            LockSupport.parkNanos(CONSISTENCY_POLL_INTERVAL.toNanos())
            !Thread.currentThread().isInterrupted
        }
    }
}

/**
 * isBefore은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param minimumPosition 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
 */
private fun CampaignProjectionSnapshot.isBefore(minimumPosition: Long?): Boolean =
    minimumPosition != null && positions.projectionPosition < minimumPosition

/**
 * toHttp은 프로모션 바우처의 애플리케이션 경계에서 인증·tenant scope·입력 형식을 확인하고 성공 결과와 업무 오류를 계약된 응답으로 매핑합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param clock 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
 */
private fun CampaignProjectionReadModel.toHttp(clock: Clock): CampaignHttpResponse =
    CampaignHttpResponse(
        campaignId = campaignId,
        state = state.name,
        revision = streamVersion - 1,
        policyVersion = policyVersion - 1,
        capacity = capacity,
        allocatedCount = allocatedCount,
        remainingCapacity = (capacity - allocatedCount).coerceAtLeast(0),
        startsAt = startsAt,
        endsAt = endsAt,
        observedAt = clock.instant(),
    )
