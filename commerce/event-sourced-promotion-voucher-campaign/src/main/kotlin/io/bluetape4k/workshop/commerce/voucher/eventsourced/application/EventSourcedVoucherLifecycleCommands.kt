    private val voucherEvents = VoucherEventCodec()

    /**
     * `redeem`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = redeem(input = input)
     * ```
     * @param input 요청 경계에서 검증된 `input`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    override fun redeem(input: RedeemVoucherCommandInput): VoucherCommandExecution {
        val command = input.validated()
        val now = clock.instant()
        return execute(
            VoucherLifecycleCommandContext(
                tenant = command.tenant,
                principal = command.principal,
                idempotencyKey = command.idempotencyKey,
                voucherId = command.voucherId,
                operation = "REDEEM",
                fingerprintMaterial = listOf(
                    command.code,
                    command.expectedRevision,
                    command.redemptionReference
                ).joinToString("\u0000"),
                now = now,
            ),
        ) { authority ->
            decideRedeem(command, authority, now)
        }
    }

    /**
     * `release`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = release(input = input)
     * ```
     * @param input 요청 경계에서 검증된 `input`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    override fun release(input: ReleaseVoucherCommandInput): VoucherCommandExecution {
        val command = input.validated()
        val now = clock.instant()
        return execute(
            VoucherLifecycleCommandContext(
                tenant = command.tenant,
                principal = command.principal,
                idempotencyKey = command.idempotencyKey,
                voucherId = command.voucherId,
                operation = "RELEASE",
                fingerprintMaterial = command.expectedRevision.toString(),
                now = now,
            ),
        ) { authority ->
            decideRelease(command, authority, now)
        }
    }

    /**
     * execute은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param context 업무 처리에 필요한 context 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param decide 업무 처리에 필요한 decide 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun execute(
        context: VoucherLifecycleCommandContext,
        decide: (VoucherLifecycleAuthority) -> EventSourcedCommandDecision,
    ): VoucherCommandExecution {
        val tenantId = TenantId(context.tenant)
        val subject = identities.resolve(tenantId, "voucher-subject", context.principal)

        val principalDigest = keyRing.digest(
            HmacPurpose.PRINCIPAL_SCOPE,
            tenantId,
            "voucher-${context.operation}",
            context.principal,
        )
        val keyDigest = keyRing.digest(
            HmacPurpose.IDEMPOTENCY_KEY,
            tenantId,
            "voucher-${context.operation}:${context.voucherId}:${principalDigest.value}",
            context.idempotencyKey,
        )
        val scope = ReceiptScope(
            tenantId = tenantId,
            principalDigest = ReceiptDigest.of(principalDigest.value),
            operation = context.operation,
            resourceId = context.voucherId.toString(),
            keyDigest = ReceiptDigest.of(keyDigest.value),
        )
        val execution = commands.execute(
            EventSourcedCommand(
                scope = scope,
                fingerprint = ReceiptDigest.sha256(
                    "voucher-${context.operation}-v1\u0000${context.fingerprintMaterial}",
                ),
                acquiredAt = context.now,
                decideAfterRehydrate = {
                    decide(loadAuthority(tenantId, context.voucherId, subject))
                },
            ),
        ).toVoucherExecution()

        log.debug { "voucher_lifecycle_command operation=${context.operation} voucherId=${context.voucherId}" }
        return execution
    }

    /**
     * loadAuthority은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param voucherId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param subject 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     */
    private fun loadAuthority(
        tenantId: TenantId,
        voucherId: UUID,
        subject: SubjectIdentity,
    ): VoucherLifecycleAuthority {
        val stream = StreamKey(tenantId, "voucher", voucherId)
        val voucher = vouchers.voucherInCurrentTransaction(tenantId.value, voucherId)
        return VoucherLifecycleAuthority(stream, voucher, subject)
    }

    /**
     * decideRedeem은 프로모션 바우처의 재고·할당량·금액을 검증한 뒤 한 번만 상태 전이시키고, 충돌·재시도·보상 결과를 감사 가능한 형태로 남깁니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param authority 업무 처리에 필요한 authority 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun decideRedeem(
        command: RedeemVoucherCommandInput,
        authority: VoucherLifecycleAuthority,
        now: Instant,
    ): EventSourcedCommandDecision {
        val voucher = authority.ownedVoucher()
            ?: return rejected(
                ReceiptOutcome.VOUCHER_NOT_FOUND,
                NOT_FOUND_STATUS,
                authority.subject,
                command.voucherId,
                now,
            )

        val outcome = when {
            voucher.publicRevision != command.expectedRevision -> ReceiptOutcome.STALE_REVISION
            voucher.state != VoucherState.ALLOCATED            -> ReceiptOutcome.INVALID_TRANSITION
            !now.isBefore(checkNotNull(voucher.expiresAt))     -> ReceiptOutcome.VOUCHER_EXPIRED
            !validCode(command, voucher)                       -> ReceiptOutcome.INVALID_VOUCHER_CODE
            else                                               -> null
        }
        return outcome?.let { rejected(it, it.failureStatus, authority.subject, command.voucherId, now) }
            ?: accepted(
                event = VoucherEvent.VoucherRedeemed(now),
                outcome = ReceiptOutcome.VOUCHER_REDEEMED,
                authority = authority,
                now = now
            )
    }

    /**
     * decideRelease은 프로모션 바우처의 동시 작업에서 한 실행자만 처리하도록 lease·lock을 원자적으로 획득·갱신하고 만료·소유자 불일치를 거절합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param authority 업무 처리에 필요한 authority 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun decideRelease(
        command: ReleaseVoucherCommandInput,
        authority: VoucherLifecycleAuthority,
        now: Instant,
    ): EventSourcedCommandDecision {
        val voucher = authority.ownedVoucher()
            ?: return rejected(
                ReceiptOutcome.VOUCHER_NOT_FOUND,
                NOT_FOUND_STATUS,
                authority.subject,
                command.voucherId,
                now,
            )
        val outcome = when {
            voucher.publicRevision != command.expectedRevision -> ReceiptOutcome.STALE_REVISION
            voucher.state != VoucherState.ALLOCATED            -> ReceiptOutcome.INVALID_TRANSITION
            else                                               -> null
        }
        return outcome?.let { rejected(it, it.failureStatus, authority.subject, command.voucherId, now) }
            ?: accepted(
                event = VoucherEvent.VoucherReleased,
                outcome = ReceiptOutcome.VOUCHER_RELEASED,
                authority = authority,
                now = now
            )
    }

    /**
     * validCode은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param voucher 업무 처리에 필요한 voucher 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun validCode(
        command: RedeemVoucherCommandInput,
        voucher: VoucherAggregate,
    ): Boolean {
        val expected = vouchers.voucherCode(
            tenant = command.tenant,
            campaignId = checkNotNull(voucher.campaignId),
            allocationId = command.voucherId,
            keyVersion = checkNotNull(voucher.verificationKeyVersion),
        )
        return MessageDigest.isEqual(command.code.toUtf8Bytes(), expected.toUtf8Bytes())
    }

    /**
     * accepted은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param outcome 허용된 업무 상태 또는 처리 결과입니다. 임의의 문자열을 다음 전이 기준으로 사용하지 않습니다.
     * @param authority 업무 처리에 필요한 authority 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun accepted(
        event: VoucherEvent,
        outcome: ReceiptOutcome,
        authority: VoucherLifecycleAuthority,
        now: Instant,
    ): EventSourcedCommandDecision =
        EventSourcedCommandDecision(
            appends = listOf(
                ExpectedAppend(
                    stream = authority.stream,
                    expectedVersion = checkNotNull(authority.voucher).version,
                    events = listOf(event.toAppend(authority.subject, now)),
                ),
            ),
            descriptor = TerminalDescriptor(
                outcome = outcome,
                status = SUCCESS_STATUS,
                keyVersions = TerminalKeyVersions(hmac = authority.subject.hmacKeyVersion),
                allocationId = checkNotNull(authority.voucher.voucherId),
            ).withObservedAt(now),
        )

    /**
     * toAppend은 프로모션 바우처 변경을 outbox·이벤트 계약으로 전달하되 commit 순서, partition key, 중복 소비 방지와 재전송 결과를
     * 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param subject 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun VoucherEvent.toAppend(
        subject: SubjectIdentity,
        now: Instant,
    ): EventToAppend {
        val serialized = voucherEvents.encode(this)
        val eventId = Uuid.V7.nextUUID()

        return EventToAppend(
            eventId = eventId,
            eventType = serialized.eventType,
            schemaVersion = 1,
            payload = EventPayload(serialized.payload.canonicalJson),
            occurredAt = now,
            correlationId = eventId.toString(),
            actorSurrogate = subject.surrogate.toString(),
            actorHmacKeyVersion = subject.hmacKeyVersion,
        )
    }

    private companion object: KLogging()
}
/**
 * VoucherLifecycleAuthority은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property stream 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property voucher 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property subject 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


private data class VoucherLifecycleAuthority(
    /**
     * `stream`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val stream: StreamKey,
    /**
     * `voucher`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val voucher: VoucherAggregate?,
    /**
     * `subject`은 바우처·프로모션에서 권한과 데이터 범위를 판정하는 호출 주체 또는 소유자 정보입니다.
     *
     * 인증·인가 경계를 통과한 값만 사용하고 다른 tenant의 상태·payload가 섞이지 않도록 합니다.
     */
    val subject: SubjectIdentity,
) {
    /**
     * `ownedVoucher`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = ownedVoucher()
     * ```
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    fun ownedVoucher(): VoucherAggregate? =
        voucher?.takeIf { it.subjectId == subject.surrogate }
}

/**
 * `VoucherAggregate`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
 *
 * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
 */
private val VoucherAggregate.publicRevision: Long get() = version - 2

/**
 * `ReceiptOutcome`은 바우처·프로모션에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
 *
 * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
 */
private val ReceiptOutcome.failureStatus: Int
    get() = if (this == ReceiptOutcome.STALE_REVISION) PRECONDITION_FAILED_STATUS else CONFLICT_STATUS

/**
 * rejected은 프로모션 바우처의 취소·보상·종료 전이를 허용된 terminal 규칙에 따라 적용하고, 이미 처리된 요청은 멱등하게 유지합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param outcome 허용된 업무 상태 또는 처리 결과입니다. 임의의 문자열을 다음 전이 기준으로 사용하지 않습니다.
 * @param status 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
 * @param subject 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
 * @param voucherId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
 * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
 */
private fun rejected(
    outcome: ReceiptOutcome,
    status: Int,
    subject: SubjectIdentity,
    voucherId: UUID,
    now: Instant,
): EventSourcedCommandDecision =
    EventSourcedCommandDecision(
        appends = emptyList(),
        descriptor = TerminalDescriptor(
            outcome = outcome,
            status = status,
            keyVersions = TerminalKeyVersions(hmac = subject.hmacKeyVersion),
            allocationId = voucherId,
        ).withObservedAt(now),
    )
/**
 * VoucherLifecycleCommandContext은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property tenant 프로모션 바우처 요청이 속한 테넌트 식별자입니다. 저장·이벤트·멱등성 범위를 이 값으로 분리해 다른 고객의 데이터가 섞이지 않게 합니다.
 * @property principal 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property idempotencyKey 무결성·인증·멱등성 검증에 사용하는 보안 자료입니다. 원문 비밀값을 로그나 일반 응답에 노출하지 않고 변조 여부를 확인합니다.
 * @property voucherId 업무 객체의 불변 식별자입니다. API·영속화·이벤트가 같은 대상을 가리키도록 생성 후 변경하지 않습니다.
 * @property operation 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property fingerprintMaterial 무결성·인증·멱등성 검증에 사용하는 보안 자료입니다. 원문 비밀값을 로그나 일반 응답에 노출하지 않고 변조 여부를
 * 확인합니다.
 * @property now 프로모션 바우처의 업무 시각입니다. 만료·정렬·재시도·SLA 판정에 사용하므로 저장소와 API에서 동일한 시간대와 clock 정책을 유지합니다.
 */


private data class VoucherLifecycleCommandContext(
    /**
     * `tenant`은 바우처·프로모션에서 권한과 데이터 범위를 판정하는 호출 주체 또는 소유자 정보입니다.
     *
     * 인증·인가 경계를 통과한 값만 사용하고 다른 tenant의 상태·payload가 섞이지 않도록 합니다.
     */
    val tenant: String,
    /**
     * `principal`은 바우처·프로모션에서 권한과 데이터 범위를 판정하는 호출 주체 또는 소유자 정보입니다.
     *
     * 인증·인가 경계를 통과한 값만 사용하고 다른 tenant의 상태·payload가 섞이지 않도록 합니다.
     */
    val principal: String,
    /**
     * `idempotencyKey`은 바우처·프로모션에서 멱등성·무결성·lease fencing을 확인하는 보호 값입니다.
     *
     * 원문 비밀값을 로그·일반 응답에 노출하지 않고 재시도와 오래된 worker를 안전하게 차단합니다.
     */
    val idempotencyKey: String,
    /**
     * `voucherId`은 바우처·프로모션에서 업무 대상의 불변 식별자입니다.
     *
     * 생성 후 변경하지 않으며 API·영속화·이벤트가 같은 대상을 가리키도록 유지합니다.
     */
    val voucherId: UUID,
    /**
     * `operation`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val operation: String,
    /**
     * `fingerprintMaterial`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val fingerprintMaterial: String,
    /**
     * `now`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val now: Instant,
