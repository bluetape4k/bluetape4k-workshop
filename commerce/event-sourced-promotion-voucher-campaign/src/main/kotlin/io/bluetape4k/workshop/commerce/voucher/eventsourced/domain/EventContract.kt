     */
    val actorHmacKeyVersion: Int = 1,
) {
    /**
     * 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
     */
    val canonicalChecksum: String by lazy { checksumOf(canonicalFields()) }

    init {
        eventId.version().requireEquals(UUID_V7, "eventId.version")
        globalPosition.requirePositiveNumber("globalPosition")
        eventType.requireNotBlank("eventType")
        schemaVersion.requireInRange(1, Int.MAX_VALUE, "schemaVersion")
        correlationId.requireNotBlank("correlationId")
        actorSurrogate.requireNotBlank("actorSurrogate")
        actorHmacKeyVersion.requirePositiveNumber("actorHmacKeyVersion")
        recordedAt.requireGe(occurredAt, "recordedAt")
    }

    /**
     * canonicalFields은 프로모션 바우처 경계의 payload를 계약된 스키마와 canonical 표현으로 변환하고, 누락·버전 불일치·무결성 오류를 업무
     * 오류로 분류합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    private fun canonicalFields(): List<Any> =
        listOf(
            eventId,
            tenantId.value,
            stream.type,
            stream.id,
            stream.version,
            globalPosition,
            eventType,
            schemaVersion,
            occurredAt,
            recordedAt,
            correlationId,
            causationId.orEmpty(),
            actorSurrogate,
            actorHmacKeyVersion,
            payload.canonicalJson,
        )

    private companion object {
        /**
         * checksumOf은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param fields 업무 처리에 필요한 fields 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         */
        fun checksumOf(fields: List<Any>): String =
            fields
                .joinToString("|")
                .let(Digesters.SHA256::digestHexUtf8)
    }
}
