/**
 * EventPayload은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property canonicalJson 프로모션 바우처 경계에서 전달되는 업무 내용입니다. 스키마·크기·무결성을 검증한 뒤 저장·발행하며 후속 상태 전이에 필요한 정보만
 * 포함합니다.
 */


internal data class EventPayload(val canonicalJson: String) {
    init {
        canonicalJson.requireNotBlank("payload")
        payloadByteSize().requireLe(MAX_EVENT_PAYLOAD_BYTES, "payload.bytes")
        SENSITIVE_FIELD_NAMES.none(::containsField).requireEquals(true, "payload.excludesSensitiveFields")
        validateJsonBounds(canonicalJson)
    }

    /**
     * payloadByteSize은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    private fun payloadByteSize(): Int = canonicalJson.toUtf8Bytes().size

    /**
     * containsField은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param fieldName 업무 처리에 필요한 fieldName 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun containsField(fieldName: String): Boolean =
        canonicalJson.contains("\"$fieldName\"", ignoreCase = true)

    private companion object {
        /**
         * `SENSITIVE_FIELD_NAMES`은 바우처·프로모션에서 저장 객체·외부 리소스·전송 경계를 가리키는 참조 값입니다.
         *
         * allowlist·sanitize·소유권 검사를 거친 뒤 API·저장소·이벤트에서 동일한 key 규칙을 사용합니다.
         */
        val SENSITIVE_FIELD_NAMES = setOf(
            "voucherCode",
            "email",
            "phone",
            "accessToken",
            "token",
            "idempotencyKey",
            "authorization",
            "authorizationHeader",
            "user",
            "userId",
            "device",
            "deviceId",
            "ip",
            "ipAddress",
        )

        /**
         * validateJsonBounds은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을
         * 막습니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param json 업무 처리에 필요한 json 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         */
        fun validateJsonBounds(json: String) {
            var depth = 0
            var stringBytes = 0
            var inString = false
            var escaped = false
            json.forEach { char ->
                if (inString) {
                    when {
                        escaped     -> escaped = false
                        char == '\\' -> escaped = true
                        char == '"' -> {
                            inString = false
                            stringBytes = 0
                        }
                        else        -> {
                            stringBytes += char.toString().toUtf8Bytes().size
                            stringBytes.requireLe(MAX_EVENT_PAYLOAD_STRING_BYTES, "payload.stringBytes")
                        }
                    }
                } else {
                    depth = updateDepth(char, depth)
                    if (char == '"') inString = true
                }
            }
            (!inString && depth == 0).requireEquals(true, "payload.balancedJson")
        }

        /**
         * updateDepth은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param char 업무 처리에 필요한 char 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         * @param depth 업무 처리에 필요한 depth 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         */
        private fun updateDepth(char: Char, depth: Int): Int {
            val nextDepth =
                when (char) {
                    '{', '[' -> depth + 1
                    '}', ']' -> depth - 1
                    else -> depth
                }
            return nextDepth
                .requireZeroOrPositiveNumber("payload.depth")
                .requireLe(MAX_EVENT_PAYLOAD_DEPTH, "payload.depth")
        }
    }
}
