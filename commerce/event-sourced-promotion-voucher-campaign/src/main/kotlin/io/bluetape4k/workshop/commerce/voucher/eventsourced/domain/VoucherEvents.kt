/**
 * `TENANT_ID_MAX_LENGTH`은 바우처·프로모션에서 권한과 데이터 범위를 판정하는 호출 주체 또는 소유자 정보입니다.
 *
 * 인증·인가 경계를 통과한 값만 사용하고 다른 tenant의 상태·payload가 섞이지 않도록 합니다.
 */
private const val TENANT_ID_MAX_LENGTH = 64

@JvmInline
/**
 * TenantId은 이벤트 소싱 프로모션 바우처 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
value class TenantId private constructor(val value: String) {
    companion object {
        /**
         * invoke은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param value 업무 처리에 필요한 value 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
         */
        operator fun invoke(value: String): TenantId {
            val validValue = value.requireNotBlank("tenantId")
            val validLength = validValue.length.requireInRange(
                1,
                TENANT_ID_MAX_LENGTH,
                "tenantId.length",
            )
            return TenantId(validValue.take(validLength))
        }
    }
}

/**
 * `CampaignState`은 수명주기 상태입니다.
 * 저장·이벤트·API 응답에서 같은 이름을 사용하며, 허용되지 않은 상태 전이는 거부해야 합니다.
 */
internal enum class CampaignState {
    /**
     * `CampaignState.DRAFT`은 검증·승인 전의 초안 상태입니다.
     */
    DRAFT,
    /**
     * `CampaignState.ACTIVE`은 해당 기능이나 정책이 현재 요청 처리에 적용되는 값입니다.
     */
    ACTIVE,
    /**
     * `CampaignState.PAUSED`은 운영자가 신규 진행을 중단하고 재개 명령을 기다리는 값입니다.
     */
    PAUSED,
    /**
     * `CampaignState.ENDED`은 `ended` 업무 상황을 나타냅니다. 현재 상태에서 허용된 다음 전이와 terminal 여부를 확인합니다.
