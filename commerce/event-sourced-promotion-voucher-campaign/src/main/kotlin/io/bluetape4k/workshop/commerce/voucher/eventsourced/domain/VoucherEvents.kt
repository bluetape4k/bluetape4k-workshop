             * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
             * @param campaignId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
             * @param voucherId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
             * @param subjectId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
             * @param codeKeyVersions 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
             */
            operator fun invoke(
                tenantId: TenantId,
                campaignId: UUID,
                voucherId: UUID,
                subjectId: UUID,
                codeKeyVersions: VoucherCodeKeyVersions = VoucherCodeKeyVersions(),
            ): VoucherIssued =
                VoucherIssued(
                    tenantId = tenantId,
                    campaignId = campaignId,
                    voucherId = voucherId,
                    subjectId = subjectId,
                    codeKeyVersions = codeKeyVersions,
                )
        }
    }
