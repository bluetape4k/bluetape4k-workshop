        val finalVersions: Map<StreamKey, Long>,
        /**
         * `firstGlobalPosition`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
         *
         * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
         */
        val firstGlobalPosition: Long,
        /**
         * `lastGlobalPosition`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
         *
         * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
         */
        val lastGlobalPosition: Long,
    ) : AppendResult {
        init {
            finalVersions.requireNotEmpty("finalVersions")
            firstGlobalPosition.requirePositiveNumber("firstGlobalPosition")
            lastGlobalPosition.requireGe(firstGlobalPosition, "lastGlobalPosition")
        }
    }
/**
 * Conflict은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property stream 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property expectedVersion 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 * @property actualVersion 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 */


    data class Conflict(
        /**
         * `stream`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val stream: StreamKey,
        /**
         * `expectedVersion`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
         *
         * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
         */
        val expectedVersion: Long,
        /**
         * `actualVersion`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
         *
         * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
         */
        val actualVersion: Long,
    ) : AppendResult
/**
 * DuplicateEvent은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property eventId 이벤트의 불변 식별자입니다. inbox/outbox 중복 제거와 감사 추적의 기준이므로 재시도에도 같은 값을 유지합니다.
 */


    data class DuplicateEvent(val eventId: UUID) : AppendResult
}

/**
 * EventStorePort은 이벤트 소싱 프로모션 바우처 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
 * 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
internal interface EventStorePort {
    /**
     * load은 프로모션 바우처의 commit된 source-of-truth를 읽어 호출자에게 반환하며, 알림이나 캐시만으로 현재 상태를 추정하지 않습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param read 업무 처리에 필요한 read 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    fun load(read: EventStoreRead): EventPage

    /**
     * command orchestration이 이미 소유한 transaction을 통해 load합니다.
     *
     * 구현체는 두 번째 transaction을 열거나 nested database permit을 얻지 않도록 이를 override할 수 있습니다.
     * test double은 기본적으로 일반 bounded load를 사용합니다.
     */
    fun loadInCurrentTransaction(read: EventStoreRead): EventPage = load(read)

    /**
     * appendAll은 프로모션 바우처 변경을 outbox·이벤트 계약으로 전달하되 commit 순서, partition key, 중복 소비 방지와 재전송 결과를
     * 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param appends 업무 처리에 필요한 appends 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    fun appendAll(appends: List<ExpectedAppend>): AppendResult
}

/**
 * nextVersion은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
 *
 * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
 */
internal fun ExpectedAppend.nextVersion(): Long = expectedVersion + events.size
