     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val resolvedAt: Instant?,
)

/**
 * `ProjectionPoisonState`은 수명주기 상태입니다.
 * 저장·이벤트·API 응답에서 같은 이름을 사용하며, 허용되지 않은 상태 전이는 거부해야 합니다.
 */
internal enum class ProjectionPoisonState {
    /**
     * `ProjectionPoisonState.FAILED`은 처리가 실패했으며 재시도 가능 여부를 별도 정책으로 판단해야 하는 값입니다.
     */
    FAILED,
    /**
     * `ProjectionPoisonState.RESOLVED`은 `resolved` 업무 상황을 나타냅니다. 현재 상태에서 허용된 다음 전이와 terminal 여부를
     * 확인합니다.
     */
    RESOLVED,
}

/**
 * projection state는 disposable로 유지합니다. current fenced owner가 PostgreSQL lease row lock을 보유하는 동안에만
 * event identity, read-model mutation, checkpoint advance가 함께 commit됩니다.
 * @property leases 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
 * @property campaigns 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property poisons 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class ProjectionRepository(
    /**
     * `leases`은 바우처·프로모션에서 멱등성·무결성·lease fencing을 확인하는 보호 값입니다.
     *
     * 원문 비밀값을 로그·일반 응답에 노출하지 않고 재시도와 오래된 worker를 안전하게 차단합니다.
     */
    private val leases: ProjectionLeaseRepository,
    /**
     * `campaigns`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val campaigns: CampaignProjectionStore = CampaignProjectionStore(),
    /**
     * `poisons`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val poisons: ProjectionPoisonStore = ProjectionPoisonStore(),
) {

    companion object: KLogging()

    /**
     * applyBatch은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param events 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    fun applyBatch(
        key: ProjectionKey,
        lease: ProjectionLease,
        events: List<EventEnvelope>,
        now: Instant,
    ): ProjectionApplyResult {
        TransactionManager.current()
        validateBatch(events)
        leases.requireActive(key.projection, key.generation, lease, now)
        val result = events.fold(ProjectionMutationCount()) { count, event ->
            applyEvent(key, lease, event, now, count)
        }
        val checkpoint = advanceCheckpoint(key, lease, events, now)
        return ProjectionApplyResult(
            appliedEventCount = result.applied,
            duplicateEventCount = result.duplicates,
            checkpoint = checkpoint
        )
    }

    /**
     * checkpoint은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     */
    fun checkpoint(key: ProjectionKey): ProjectionCheckpoint? {
        TransactionManager.current()
        return ProjectionCheckpoints
            .selectAll()
            .where { checkpointPredicate(key) }
            .singleOrNull()
            ?.let(::toCheckpoint)
    }

    /**
     * readModel은 프로모션 바우처의 commit된 source-of-truth를 읽어 호출자에게 반환하며, 알림이나 캐시만으로 현재 상태를 추정하지 않습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param streamType 업무 처리에 필요한 streamType 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param streamId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     */
    fun readModel(
        key: ProjectionKey,
        streamType: String,
        streamId: UUID,
    ): ProjectionReadModel? {
        TransactionManager.current()
        return ProjectionReadModels
            .selectAll()
            .where {
                keyPredicate(ProjectionReadModels.projection, ProjectionReadModels.generation, key) and
                        (ProjectionReadModels.streamType eq streamType) and
                        (ProjectionReadModels.streamId eq streamId)
            }.singleOrNull()
            ?.let(::toReadModel)
    }

    /**
     * campaign은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param campaignId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     */
    fun campaign(
        key: ProjectionKey,
        tenantId: TenantId,
        campaignId: UUID,
    ): CampaignProjectionReadModel? {
        TransactionManager.current()
        return campaigns.find(key, tenantId, campaignId)
    }

    /**
     * poison은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param reasonClass 업무 처리에 필요한 reasonClass 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    fun poison(
        key: ProjectionKey,
        lease: ProjectionLease,
        event: EventEnvelope,
        reasonClass: String,
        now: Instant,
    ): ProjectionPoisonRecord {
        TransactionManager.current()
        val validReasonClass = reasonClass.requireNotBlank("reasonClass")
        leases.requireActive(key.projection, key.generation, lease, now)
        return poisons.recordFailure(key, event, validReasonClass, now)
    }

    /**
     * resolvePoison은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께
     * 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    fun resolvePoison(
        key: ProjectionKey,
        lease: ProjectionLease,
        event: EventEnvelope,
        now: Instant,
    ): ProjectionApplyResult {
        TransactionManager.current()
        val poison = poisons.find(key, event.eventId).checkNotNull { "poison event does not exist" }
        check(poison.state == ProjectionPoisonState.FAILED) { "poison event is already resolved" }
        check(poison.attempts <= MAX_PROJECTION_POISON_ATTEMPTS) { "poison retry limit is exhausted" }
        check(!now.isBefore(poison.nextRetryAt)) { "poison retry backoff has not elapsed" }

        val result = applyBatch(key, lease, listOf(event), now)
        poisons.resolve(key, event.eventId, now)
        log.debug { "resolve poison. result=$result" }
        return result
    }

    /**
     * applyEvent은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param count 한 번에 처리할 상한입니다. backpressure와 운영 자원 한도를 넘지 않도록 적용합니다.
     */
    private fun applyEvent(
        key: ProjectionKey,
        lease: ProjectionLease,
        event: EventEnvelope,
        now: Instant,
        count: ProjectionMutationCount,
    ): ProjectionMutationCount {
        val inserted =
            ProjectionProcessedEvents.insertIgnore { row ->
                row[ProjectionProcessedEvents.projection] = key.projection
                row[ProjectionProcessedEvents.generation] = key.generation
                row[ProjectionProcessedEvents.eventId] = event.eventId
                row[ProjectionProcessedEvents.globalPosition] = event.globalPosition
                row[ProjectionProcessedEvents.processedAt] = now
            }.insertedCount == 1
        if (!inserted) {
            return count.duplicate()
        }
        upsertReadModel(key, lease, event, now)
        campaigns.apply(key, lease, event, now)
        return count.applied()
    }

    /**
     * upsertReadModel은 프로모션 바우처의 commit된 source-of-truth를 읽어 호출자에게 반환하며, 알림이나 캐시만으로 현재 상태를 추정하지
     * 않습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param event 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun upsertReadModel(
        key: ProjectionKey,
        lease: ProjectionLease,
        event: EventEnvelope,
        now: Instant,
    ) {
        ProjectionReadModels.insertIgnore { row ->
            row[ProjectionReadModels.projection] = key.projection
            row[ProjectionReadModels.generation] = key.generation
            row[ProjectionReadModels.tenantId] = event.tenantId.value
            row[ProjectionReadModels.streamType] = event.stream.type
            row[ProjectionReadModels.streamId] = event.stream.id
            row[ProjectionReadModels.streamVersion] = event.stream.version
            row[ProjectionReadModels.globalPosition] = event.globalPosition
            row[ProjectionReadModels.eventType] = event.eventType
            row[ProjectionReadModels.payloadDigest] = event.canonicalChecksum
            row[ProjectionReadModels.fencingToken] = lease.fencingToken
            row[ProjectionReadModels.updatedAt] = now
        }
        ProjectionReadModels.update(
            where = {
                keyPredicate(ProjectionReadModels.projection, ProjectionReadModels.generation, key) and
                        (ProjectionReadModels.tenantId eq event.tenantId.value) and
                        (ProjectionReadModels.streamType eq event.stream.type) and
                        (ProjectionReadModels.streamId eq event.stream.id) and
                        (ProjectionReadModels.streamVersion less event.stream.version) and
                        (ProjectionReadModels.fencingToken lessEq lease.fencingToken)
            },
        ) { row ->
            row[ProjectionReadModels.streamVersion] = event.stream.version
            row[ProjectionReadModels.globalPosition] = event.globalPosition
            row[ProjectionReadModels.eventType] = event.eventType
            row[ProjectionReadModels.payloadDigest] = event.canonicalChecksum
            row[ProjectionReadModels.fencingToken] = lease.fencingToken
            row[ProjectionReadModels.updatedAt] = now
        }
    }

    /**
     * advanceCheckpoint은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param events 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun advanceCheckpoint(
        key: ProjectionKey,
        lease: ProjectionLease,
        events: List<EventEnvelope>,
        now: Instant,
    ): ProjectionCheckpoint {
        val position = events.maxOfOrNull(EventEnvelope::globalPosition) ?: return currentCheckpoint(key, lease, now)

        ProjectionCheckpoints.insertIgnore { row ->
            row[ProjectionCheckpoints.projection] = key.projection
            row[ProjectionCheckpoints.generation] = key.generation
            row[ProjectionCheckpoints.position] = position
            row[ProjectionCheckpoints.fencingToken] = lease.fencingToken
            row[ProjectionCheckpoints.updatedAt] = now
        }
        ProjectionCheckpoints.update(
            where = {
                checkpointPredicate(key) and
                        (ProjectionCheckpoints.position less position) and
                        (ProjectionCheckpoints.fencingToken lessEq lease.fencingToken)
            },
        ) { row ->
            row[ProjectionCheckpoints.position] = position
            row[ProjectionCheckpoints.fencingToken] = lease.fencingToken
            row[ProjectionCheckpoints.updatedAt] = now
        }
        return currentCheckpoint(key, lease, now)
    }

    /**
     * currentCheckpoint은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param lease 업무 처리에 필요한 lease 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param now 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    private fun currentCheckpoint(
        key: ProjectionKey,
        lease: ProjectionLease,
        now: Instant,
    ): ProjectionCheckpoint =
        checkpoint(key)
            ?: ProjectionCheckpoint(position = 0, fencingToken = lease.fencingToken, updatedAt = now)

}
/**
 * ProjectionMutationCount은 프로모션 바우처에서 전달되는 불변 데이터 모델입니다.
 * @property applied 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property duplicates 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


private data class ProjectionMutationCount(
    /**
     * `applied`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val applied: Int = 0,
    /**
     * `duplicates`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val duplicates: Int = 0,
) {
    /**
     * applied은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun applied(): ProjectionMutationCount = copy(applied = applied + 1)

    /**
     * duplicate은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun duplicate(): ProjectionMutationCount = copy(duplicates = duplicates + 1)
}

/**
 * validateBatch은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param events 프로모션 바우처 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
 */
private fun validateBatch(events: List<EventEnvelope>) {
    events.size.requireLe(MAX_PROJECTION_BATCH_EVENTS, "projection batch size")
    events.map(EventEnvelope::eventId).toSet().size.requireEquals(events.size, "uniqueEventIds.size")
    events
        .zipWithNext()
        .all { (current, next) -> current.globalPosition < next.globalPosition }
        .requireEquals(true, "projectionBatch.globallyOrdered")
    val payloadBytes = events.sumOf { event -> event.payload.canonicalJson.toUtf8Bytes().size }
    payloadBytes.requireLe(MAX_PROJECTION_BATCH_BYTES, "projection batch payload bytes")
}

/**
 * checkpointPredicate은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
 */
private fun checkpointPredicate(key: ProjectionKey) =
    keyPredicate(ProjectionCheckpoints.projection, ProjectionCheckpoints.generation, key)

/**
 * keyPredicate은 프로모션 바우처 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param projection 업무 처리에 필요한 projection 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 * @param generation 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
 * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
 */
private fun keyPredicate(
    projection: Column<String>,
    generation: Column<Long>,
    key: ProjectionKey,
) =
    (projection eq key.projection) and (generation eq key.generation)

/**
 * toCheckpoint은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
 *
