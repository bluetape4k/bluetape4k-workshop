/**
 * campaign -> claim -> review lock 순서 아래에서 review decision을 적용합니다.
 * @property transactions 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property campaigns 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property claims 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property reviews 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property audits 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property codes 프로모션 바우처의 상태·분류·오류 코드를 나타냅니다. 허용된 전이와 재시도·응답 분기를 선택하는 기준입니다.
 * @property clock 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
@Service
internal class ReviewCommandService(
    /**
     * `transactions`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val transactions: VoucherTransactionRunner,
    /**
     * `campaigns`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val campaigns: CampaignRepository,
    /**
     * `claims`은 바우처·프로모션에서 업무 집합 또는 조회 결과입니다.
     *
     * 빈 집합·중복·정렬·페이지 경계를 정의하고 기준 저장소의 순서를 그대로 보존합니다.
     */
    private val claims: ClaimRepository,
    /**
     * `reviews`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val reviews: ReviewRepository,
    /**
     * `audits`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val audits: AuditRepository,
    /**
     * `codes`은 바우처·프로모션에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
     *
     * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
     */
    private val codes: VoucherCodeService,
    /**
     * `clock`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val clock: Clock,
) {
    companion object: KLogging() {
        /**
         * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        private val SHA_256_HEX = Regex("[0-9a-f]{64}")
    }

    /**
     * `approve`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = approve(command = command)
     * ```
     * @param command 요청 경계에서 검증된 `command`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    fun approve(command: ReviewDecisionCommand): ReviewDecisionResult =
        decide(command, approved = true)

    /**
     * `reject`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = reject(command = command)
     * ```
     * @param command 요청 경계에서 검증된 `command`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    fun reject(command: ReviewDecisionCommand): ReviewDecisionResult =
        decide(command, approved = false)

    /**
     * decide은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param approved 업무 처리에 필요한 approved 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun decide(
        command: ReviewDecisionCommand,
        approved: Boolean,
    ): ReviewDecisionResult {
        require(SHA_256_HEX.matches(command.reviewerActorDigest)) {
            "reviewerActorDigest must be a lowercase SHA-256 hex digest"
        }

        return transactions.foregroundTransaction {
            val campaign = campaigns.findPublicForUpdate(command.tenantId, command.campaignId)
                ?: fail(VoucherCommandFailure.CAMPAIGN_NOT_FOUND)

            val claim = claims.findPublicForUpdate(command.tenantId, command.claimId)
                ?: fail(VoucherCommandFailure.CLAIM_NOT_FOUND)

            val review = reviews.findOpenForUpdate(command.tenantId, command.claimId, command.reviewId)
                ?: fail(VoucherCommandFailure.REVIEW_NOT_FOUND)

            if (claim.campaignId != campaign.campaignId || review.campaignId != campaign.campaignId) {
                fail(VoucherCommandFailure.REVIEW_NOT_FOUND)
            }

            if (
                claim.revision != command.expectedClaimRevision ||
                review.revision != command.expectedReviewRevision ||
                review.expectedClaimRevision != command.expectedClaimRevision
            ) {
                fail(VoucherCommandFailure.STALE_REVISION)
            }

            val now = Instant.now(clock)
            if (approved && review.kind == ReviewKind.REDEMPTION) {
                requireCampaignRedeemable(campaign)
                if (claim.expiresAt?.let { !now.isBefore(it) } != false) {
                    fail(VoucherCommandFailure.VOUCHER_EXPIRED)
                }
            }

            val outcome = policy {
                if (approved) {
                    VoucherPolicies.approveReview(claim.toSnapshot(), command.expectedClaimRevision)
                } else {
                    VoucherPolicies.rejectReview(claim.toSnapshot(), command.expectedClaimRevision)
                }
            }
            if (outcome.capacityDelta == 1) {
                requireCampaignActive(campaign, now)
                if (campaign.allocatedCount >= campaign.capacity) fail(VoucherCommandFailure.CAPACITY_EXHAUSTED)
                if (!campaigns.tryReserve(campaign.tenantId, campaign.id, campaign.revision)) {
                    fail(VoucherCommandFailure.CONCURRENT_MODIFICATION)
                }
            }
            val updated = claim.apply(outcome.claim)
            if (!claims.transition(updated, claim.revision)) {
                fail(VoucherCommandFailure.CONCURRENT_MODIFICATION)
            }
            val status = if (approved) ReviewStatus.APPROVED else ReviewStatus.REJECTED
            if (!reviews.decide(review, status, command.reviewerActorDigest, command.expectedReviewRevision)) {
                fail(VoucherCommandFailure.CONCURRENT_MODIFICATION)
            }
            audits.append(updated.audit(if (approved) "REVIEW_APPROVED" else "REVIEW_REJECTED"))

            val code = if (approved && review.kind == ReviewKind.ALLOCATION) reconstruct(updated) else null
            log.debug { "voucher_review_decided reviewId=${review.id} claimId=${claim.claimId} status=$status" }

            ReviewDecisionResult(updated.toSnapshot(), code)
        }
    }

    /**
     * reconstruct은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param claim 업무 처리에 필요한 claim 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun reconstruct(claim: ClaimRecord): String {
        val issued = codes.reconstruct(
            input = VoucherGenerationInput(claim.tenantId, claim.campaignId, claim.allocationId),
            generationKeyVersion = claim.generationKeyVersion ?: fail(VoucherCommandFailure.REPLAY_KEY_UNAVAILABLE),
            verificationKeyVersion = claim.verificationKeyVersion ?: fail(VoucherCommandFailure.REPLAY_KEY_UNAVAILABLE),
        ) ?: fail(VoucherCommandFailure.REPLAY_KEY_UNAVAILABLE)

        if (!MessageDigest.isEqual(issued.verifier, claim.codeVerifier)) {
            fail(VoucherCommandFailure.REPLAY_KEY_UNAVAILABLE)
        }

        return issued.code
    }
}
