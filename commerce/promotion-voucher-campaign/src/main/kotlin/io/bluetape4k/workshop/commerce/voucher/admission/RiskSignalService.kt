package io.bluetape4k.workshop.commerce.voucher.admission

import io.bluetape4k.logging.KLogging
import io.bluetape4k.logging.debug
import io.bluetape4k.logging.warn
import io.bluetape4k.redis.lettuce.filter.LettuceBloomFilter
import io.bluetape4k.support.requirePositiveNumber
import io.bluetape4k.support.toUtf8Bytes
import io.bluetape4k.workshop.commerce.voucher.application.RiskSignal
import io.bluetape4k.workshop.commerce.voucher.config.VoucherDegradationState
import io.bluetape4k.workshop.commerce.voucher.config.VoucherDegradedComponent
import java.util.*
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec
/**
 * VoucherAdmissionKeyFactory은 프로모션 바우처에서 사용하는 업무 객체입니다.
 * @property version 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값이 다르면 오래된 명령을 거부합니다.
 */


internal class VoucherAdmissionKeyFactory(
    /**
     * `version`은 바우처·프로모션에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    private val version: Int,
    rateKey: ByteArray,
    riskKey: ByteArray,
) {

    private companion object: KLogging() {
        /**
         * `MINIMUM_KEY_BYTES`은 바우처·프로모션에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
         *
         * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
         */
        const val MINIMUM_KEY_BYTES = 32
        /**
         * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        const val HMAC_SHA_256 = "HmacSHA256"
        /**
         * 청구·정산 금액 또는 통화입니다. 통화 일치와 반올림 규칙을 적용한 뒤 저장합니다.
         */
        const val RATE_DOMAIN = "voucher-rate-key-v1"
        /**
         * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        const val RISK_DOMAIN = "voucher-risk-key-v1"
        /**
         * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val SEPARATOR = byteArrayOf(0)
    }
    /**
     * 청구·정산 금액 또는 통화입니다. 통화 일치와 반올림 규칙을 적용한 뒤 저장합니다.
     */

    private val rateKey = rateKey.copyOf()
    /**
     * 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
     */
    private val riskKey = riskKey.copyOf()

    init {
        version.requirePositiveNumber("version")
        require(this.rateKey.size >= MINIMUM_KEY_BYTES) { "rateKey must contain at least 32 bytes" }
        require(this.riskKey.size >= MINIMUM_KEY_BYTES) { "riskKey must contain at least 32 bytes" }
    }

    /**
     * rateKey은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param principalRef 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     * @param operation 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    fun rateKey(
        tenantId: String,
        principalRef: String,
        operation: String,
    ): String =
        "v$version:${digest(rateKey, RATE_DOMAIN, tenantId, principalRef, operation)}"

    /**
     * riskKey은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param subjectRef 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     */
    fun riskKey(
        tenantId: String,
        subjectRef: String,
    ): String =
        "v$version:${digest(riskKey, RISK_DOMAIN, tenantId, subjectRef)}"

    /**
     * digest은 프로모션 바우처 요청의 인증·권한·무결성을 확인하고, 실패 시 민감한 내부 상태를 노출하지 않은 채 업무 처리를 차단합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param key 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param domain 업무 처리에 필요한 domain 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param values 업무 처리에 필요한 values 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun digest(
        key: ByteArray,
        domain: String,
        vararg values: String,
    ): String {
        val mac = Mac.getInstance(HMAC_SHA_256)
        mac.init(SecretKeySpec(key, HMAC_SHA_256))
        mac.update(domain.toUtf8Bytes())
        values.forEach { value ->
            mac.update(SEPARATOR)
            mac.update(value.toUtf8Bytes())
        }
        return Base64.getUrlEncoder().withoutPadding().encodeToString(mac.doFinal())
    }
}

/**
 * VoucherRiskBackend은 프로모션 바우처 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
 * 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
internal interface VoucherRiskBackend {
    /**
     * add은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param digest 재전송·멱등성·무결성 확인에 사용하는 값입니다. 원문 비밀이나 개인정보를 로그에 남기지 않습니다.
     */
    fun add(digest: String)

    /**
     * mightContain은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param digest 재전송·멱등성·무결성 확인에 사용하는 값입니다. 원문 비밀이나 개인정보를 로그에 남기지 않습니다.
     */
    fun mightContain(digest: String): Boolean
}
/**
 * LettuceBloomRiskBackend은 프로모션 바우처에서 사용하는 업무 객체입니다.
 * @property bloomFilter 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */


internal class LettuceBloomRiskBackend(
    /**
     * `bloomFilter`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val bloomFilter: LettuceBloomFilter,
): VoucherRiskBackend {
    /**
     * add은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param digest 재전송·멱등성·무결성 확인에 사용하는 값입니다. 원문 비밀이나 개인정보를 로그에 남기지 않습니다.
     */
    override fun add(digest: String) =
        bloomFilter.add(digest)

    /**
     * mightContain은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param digest 재전송·멱등성·무결성 확인에 사용하는 값입니다. 원문 비밀이나 개인정보를 로그에 남기지 않습니다.
     */
    override fun mightContain(digest: String): Boolean =
        bloomFilter.contains(digest)
}

/**
 * Bloom positive를 advisory review signal로, 모든 backend error를 UNKNOWN으로 처리합니다.
 * @property keys 무결성·인증·멱등성 검증용 보안 자료입니다. 원문을 로그나 일반 응답에 노출하지 않습니다.
 * @property backend 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property degradation 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class RiskSignalService(
    /**
     * `keys`은 바우처·프로모션에서 멱등성·무결성·lease fencing을 확인하는 보호 값입니다.
     *
     * 원문 비밀값을 로그·일반 응답에 노출하지 않고 재시도와 오래된 worker를 안전하게 차단합니다.
     */
    private val keys: VoucherAdmissionKeyFactory,
    /**
     * `backend`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val backend: VoucherRiskBackend?,
    /**
     * `degradation`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val degradation: VoucherDegradationState? = null,
) {
    companion object: KLogging()

    /**
     * assess은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param subjectRef 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     */
    fun assess(
        tenantId: String,
        subjectRef: String,
    ): RiskSignal {
        val digest = keys.riskKey(tenantId, subjectRef)
        val riskBackend = backend ?: return RiskSignal.UNKNOWN

        return try {
            val signal = if (riskBackend.mightContain(digest)) RiskSignal.REVIEW else RiskSignal.CLEAR
            degradation?.recover(VoucherDegradedComponent.REDIS)
            signal
        } catch (failure: Exception) {
            degradation?.degrade(VoucherDegradedComponent.REDIS)
            log.warn { "voucher_risk_unknown backend=REDIS failure=${failure.javaClass.simpleName}" }
            RiskSignal.UNKNOWN
        }
    }

    /**
     * remember은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param subjectRef 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     */
    fun remember(
        tenantId: String,
        subjectRef: String,
    ): Boolean {
        val riskBackend = backend ?: return false

        return try {
            riskBackend.add(keys.riskKey(tenantId, subjectRef))
            degradation?.recover(VoucherDegradedComponent.REDIS)
            true
        } catch (failure: Exception) {
            degradation?.degrade(VoucherDegradedComponent.REDIS)
            log.warn { "voucher_risk_remember_failed backend=REDIS failure=${failure.javaClass.simpleName}" }
            false
        }.also { remembered ->
            log.debug { "voucher_risk_remembered success=$remembered" }
        }
    }
}
