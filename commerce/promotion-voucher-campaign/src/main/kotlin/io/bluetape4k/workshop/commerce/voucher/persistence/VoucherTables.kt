/**
 * `ReviewStatus`은 상태 코드입니다.
 * 저장·이벤트·API 응답에서 같은 이름을 사용하며, 허용되지 않은 상태 전이는 거부해야 합니다.
 */
internal enum class ReviewStatus {
    /**
     * `ReviewStatus.OPEN`은 외부 요청을 허용하는 운영 상태입니다.
     */
    OPEN,
    /**
     * `ReviewStatus.APPROVED`은 검토·정책 검증을 통과하여 다음 업무 단계를 허용하는 값입니다.
     */
    APPROVED,
    /**
     * `ReviewStatus.REJECTED`은 정책 또는 입력 검증을 통과하지 못해 요청을 수용하지 않은 값입니다.
     */
    REJECTED,
}

/**
 * `InboxStatus`은 상태 코드입니다.
 * 저장·이벤트·API 응답에서 같은 이름을 사용하며, 허용되지 않은 상태 전이는 거부해야 합니다.
 */
internal enum class InboxStatus {
    /**
     * `InboxStatus.PENDING`은 처리를 시작했거나 시작할 조건은 갖췄지만 최종 결과를 기다리는 값입니다.
     */
    PENDING,
    /**
     * `InboxStatus.CLAIMED`은 worker 또는 lease가 해당 작업의 소유권을 획득한 값입니다.
     */
    CLAIMED,
    /**
     * `InboxStatus.APPLIED`은 마이그레이션·명령·outbox 반영이 이번 호출에서 실제로 완료된 값입니다.
     */
    APPLIED,
    /**
     * `InboxStatus.IGNORED`은 `ignored` 업무 상황을 나타냅니다. 현재 상태에서 허용된 다음 전이와 terminal 여부를 확인합니다.
     */
    IGNORED,
    /**
     * `InboxStatus.CONFLICT`은 현재 revision 또는 업무 상태와 충돌하여 자동 반영할 수 없는 값입니다.
     */
    CONFLICT,
    /**
     * `InboxStatus.FAILED`은 처리가 실패했으며 재시도 가능 여부를 별도 정책으로 판단해야 하는 값입니다.
     */
    FAILED,
}

/** in-row capacity invariant를 가진 tenant-scoped campaign capacity authority입니다. */
/** in-row capacity invariant를 가진 tenant-scoped campaign capacity authority입니다. */
internal object CampaignTable: AuditableLongIdTable("voucher_campaigns") {
