        }

    /**
     * `updatePolicy`은 애플리케이션 공개 계약의 업무 진입점입니다.
     *
     * 입력은 인증 주체·tenant scope·idempotency key와 함께 검증하고, command라면 동일 revision에서 허용된 상태 전이만 수행합니다. 반환
     * snapshot은 commit된 source-of-truth로 취급하며 SSE/event 알림만으로 현재 상태를 추정하지 않습니다.
     * 예:
     * ```kotlin
     * val response = updatePolicy(command = command)
     * ```
     * @param command 요청 경계에서 검증된 `command`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    fun updatePolicy(command: CampaignPolicyCommand): CampaignSnapshot {
        val compaignCmd = CampaignTransitionCommand(command.tenantId, command.campaignId, command.expectedRevision)
        return transition(compaignCmd, "CAMPAIGN_POLICY_UPDATED") { campaign ->
            VoucherPolicies.updateCampaignPolicy(
                campaign = campaign,
                expectedRevision = command.expectedRevision,
                capacity = command.capacity,
                perUserLimit = command.perUserLimit,
                redemptionTtlSeconds = command.redemptionTtlSeconds,
            )
        }
    }

    /**
     * transition은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param command 프로모션 바우처 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param reasonCode 업무 처리에 필요한 reasonCode 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param policyTransition 업무 처리에 필요한 policyTransition 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private inline fun transition(
        command: CampaignTransitionCommand,
        reasonCode: String,
        crossinline policyTransition: (CampaignSnapshot) -> CampaignSnapshot,
    ): CampaignSnapshot =
        transactions.foregroundTransaction {
            /**
             * `persisted`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
             *
             * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
             */
            val persisted = campaigns.findPublicForUpdate(command.tenantId, command.campaignId)
                ?: fail(VoucherCommandFailure.CAMPAIGN_NOT_FOUND)

            if (persisted.revision != command.expectedRevision) {
                fail(VoucherCommandFailure.STALE_REVISION)
            }
            /**
             * `updated`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
             *
             * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
             */
            val updated = persisted.apply(policy { policyTransition(persisted.toSnapshot()) })

            if (!campaigns.transition(updated, persisted.revision)) {
                fail(VoucherCommandFailure.CONCURRENT_MODIFICATION)
            }
            audits.append(updated.auditCampaign(reasonCode))
            log.debug { "voucher_campaign_transitioned campaignId=${updated.campaignId} state=${updated.state}" }

            updated.toSnapshot()
        }
}

/**
 * apply은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param snapshot 업무 처리에 필요한 snapshot 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 */
internal fun CampaignRecord.apply(snapshot: CampaignSnapshot): CampaignRecord =
    copy(
        state = snapshot.state,
        startsAt = snapshot.startsAt,
        endsAt = snapshot.endsAt,
        capacity = snapshot.capacity,
        allocatedCount = snapshot.allocatedCount,
        perUserLimit = snapshot.perUserLimit,
        redemptionTtlSeconds = snapshot.redemptionTtlSeconds,
        policyVersion = snapshot.policyVersion,
        revision = snapshot.revision,
    )

/**
 * auditCampaign은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param reasonCode 업무 처리에 필요한 reasonCode 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 */
private fun CampaignRecord.auditCampaign(reasonCode: String): AuditRecord =
    AuditRecord(
        id = 0,
        tenantId = tenantId,
        campaignId = campaignId,
        aggregateType = "CAMPAIGN",
        aggregateId = campaignId,
        revision = revision,
        actorType = "OPERATOR",
        reasonCode = reasonCode,
        policyVersion = policyVersion,
        correlationDigest = null,
    )
