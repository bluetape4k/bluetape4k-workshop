/**
 * requireAsciiIdentifier은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을
 * 막습니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param value 업무 처리에 필요한 value 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 * @param name 업무 처리에 필요한 name 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 * @param maxLength 한 번에 처리할 상한입니다. backpressure와 운영 자원 한도를 넘지 않도록 적용합니다.
 */
internal fun requireAsciiIdentifier(
    value: String?,
    name: String,
    maxLength: Int = 64,
): String {
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    val candidate = value ?: throw invalidRequest("$name is required")
    if (candidate.length !in 1..maxLength || candidate.toUtf8Bytes().size != candidate.length) {
        throw invalidRequest("$name must contain 1..$maxLength ASCII characters")
    }
    if (candidate.any { it.code !in 0x21..0x7e }) {
        throw invalidRequest("$name contains an invalid character")
    }
    return candidate
}

