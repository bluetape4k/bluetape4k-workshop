     */
    data object LeaderActionFailed: WorkerRunResult {
        /**
         * readResolve은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
