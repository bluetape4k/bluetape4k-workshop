/**
 * scheduled 실행과 operator-triggered 실행 사이에서 local single-flight guard 하나를 공유합니다.
 * @property reconciliation 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property properties 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property leader 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property degradation 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 * @property metrics 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class VoucherReconciliationWorker(
    /**
     * `reconciliation`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val reconciliation: VoucherReconciliationService,
    /**
     * `properties`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val properties: VoucherWorkerProperties,
    /**
     * `leader`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val leader: VoucherLeaderRunner,
    /**
     * `degradation`은 바우처·프로모션에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val degradation: VoucherDegradationState? = null,
    /**
     * `metrics`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val metrics: VoucherMetrics? = null,
) {
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val running = AtomicBoolean()

    /**
     * runScheduled은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun runScheduled(): WorkerRunResult = singleFlight {
        try {
            when (val result = leader.run(::runService)) {
                is LeaderRunResult.Elected      -> {
                    degradation?.recover(VoucherDegradedComponent.LEADER)
                    metrics?.leaderState(VoucherLeaderState.ELECTED)
                    WorkerRunResult.Elected(checkNotNull(result.value), result.leaderId).also {
                        recordSuccess(it.result)
                    }
                }
                LeaderRunResult.Skipped         -> {
                    degradation?.recover(VoucherDegradedComponent.LEADER)
                    metrics?.leaderState(VoucherLeaderState.SKIPPED)
                    WorkerRunResult.LeaderSkipped
                }
                is LeaderRunResult.ActionFailed -> {
                    degradation?.degrade(VoucherDegradedComponent.LEADER)
                    metrics?.leaderState(VoucherLeaderState.DEGRADED)
                    log.warn {
                        "voucher_reconciliation_leader_action_failed " +
                                "failure=${result.cause.javaClass.simpleName}"
                    }
                    WorkerRunResult.LeaderActionFailed
                }
            }
        } catch (failure: Exception) {
            degradation?.degrade(VoucherDegradedComponent.LEADER)
            metrics?.leaderState(VoucherLeaderState.DEGRADED)
            log.warn {
                "voucher_reconciliation_leader_unavailable fallback=MANUAL " +
                        "failure=${failure.javaClass.simpleName}"
            }
            WorkerRunResult.LeaderBackendUnavailable
        }
    }

    /**
     * runManual은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun runManual(): WorkerRunResult =
        singleFlight {
            WorkerRunResult.Manual(runService())
                .also { recordSuccess(it.result) }
        }

    /**
     * recordSuccess은 프로모션 바우처 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param result 허용된 업무 상태 또는 처리 결과입니다. 임의의 문자열을 다음 전이 기준으로 사용하지 않습니다.
     */
    private fun recordSuccess(result: ReconciliationResult) {
        metrics?.workerSucceeded(
            Instant.now().epochSecond,
            result.processed + result.skipped + result.failed,
        )
    }

    /**
     * runService은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    private fun runService(): ReconciliationResult =
        reconciliation.runBatch(properties.batchSize, properties.runDeadline)

    /**
     * singleFlight은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param action 업무 처리에 필요한 action 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private inline fun singleFlight(action: () -> WorkerRunResult): WorkerRunResult {
        if (!running.compareAndSet(false, true)) {
            log.info { "voucher_reconciliation_skipped reason=LOCAL_RUN_IN_PROGRESS" }
            return WorkerRunResult.LocalRunInProgress
        }
        return try {
            action()
        } finally {
            running.set(false)
        }
    }

    companion object: KLogging()
}

/**
 * Spring Java 25 virtual-thread scheduler에서 공유 single-flight worker path를 trigger합니다.
 * @property worker 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증·영속화·이벤트 변환에서 의미를 보존합니다.
 */
internal class VoucherReconciliationScheduler(
    /**
     * `worker`은 바우처·프로모션에서 업무 규칙을 위임하는 저장소·외부 시스템 협력자입니다.
     *
     * 기준 데이터와 재시도·timeout 정책을 숨기지 않고 호출자가 결과를 복구할 수 있게 합니다.
     */
    private val worker: VoucherReconciliationWorker,
) {
    /**
     * 프로모션 바우처 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val running = AtomicBoolean(true)

    @Scheduled(
        fixedDelayString = "\${workshop.voucher.worker.interval:5s}",
        initialDelayString = "\${workshop.voucher.worker.initial-delay:5s}",
    )
    /**
     * tick은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun tick() {
        if (running.get()) {
            worker.runScheduled()
        }
    }

    /**
     * stop은 프로모션 바우처의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun stop() {
        running.set(false)
    }
}
