 * @property result 프로모션 바우처 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


    data class Manual(val result: ReconciliationResult): WorkerRunResult

    /**
