@file:Suppress("LongParameterList") // A versioned integration envelope mirrors its fixed wire contract.

package io.bluetape4k.workshop.commerce.usagebilling.billing.integration

import io.bluetape4k.jackson3.Jackson
import io.bluetape4k.logging.KLogging
import io.bluetape4k.support.requireNotBlank
import io.bluetape4k.support.requirePositiveNumber
import io.bluetape4k.workshop.commerce.shared.integration.AggregatePartitionKey
import io.bluetape4k.workshop.commerce.shared.integration.PayloadDigest
import java.io.Serializable
import java.time.Instant
import java.util.*

/**
 * local outbox transaction과 함께 저장되는 Versioned Billing event contract입니다.
 *
 * immutable payload와 digest 덕분에 receiver는 Kafka delivery와 독립적으로 durable replay decision을 내릴 수 있습니다.
 */
class BillingIntegrationEnvelope private constructor(
    /**
     * `eventId`은 사용량 과금·정산에서 업무 대상의 불변 식별자입니다.
     *
     * 생성 후 변경하지 않으며 API·영속화·이벤트가 같은 대상을 가리키도록 유지합니다.
     */
    val eventId: UUID, val eventType: String, val schemaVersion: Int, val tenantId: String,
    /**
     * `aggregateType`은 사용량 과금·정산에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
     *
     * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
     */
    val aggregateType: String, val aggregateId: String, val aggregateVersion: Long,
    /**
     * `payload`은 사용량 과금·정산에서 서비스 경계와 교환하는 내구성 메시지 또는 업무 사실입니다.
     *
     * at-least-once 전달과 중복·순서 뒤바뀜을 고려해 digest·idempotency·quarantine 규칙을 적용합니다.
     */
    val payload: String, val payloadDigest: String, val occurredAt: Instant, val recordedAt: Instant,
): Serializable {
    init {
        eventType.requireNotBlank("eventType")
        tenantId.requireNotBlank("tenantId")
        aggregateId.requireNotBlank("aggregateId")
        schemaVersion.requirePositiveNumber("schemaVersion")
        aggregateVersion.requirePositiveNumber("aggregateVersion")
        payload.requireNotBlank("payload")
    }

    /**
     * partitionKey은 사용량 계량·청구의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun partitionKey(): String = AggregatePartitionKey.of(tenantId, aggregateType, aggregateId)

    /**
     * hasValidPayloadDigest은 사용량 계량·청구 요청의 인증·권한·무결성을 확인하고, 실패 시 민감한 내부 상태를 노출하지 않은 채 업무 처리를 차단합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun hasValidPayloadDigest(): Boolean =
        PayloadDigest.matches(payload, payloadDigest)

    /**
     * wirePayload은 사용량 계량·청구 경계의 payload를 계약된 스키마와 canonical 표현으로 변환하고, 누락·버전 불일치·무결성 오류를 업무 오류로
     * 분류합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun wirePayload(): String =
        Jackson.defaultJsonMapper
            .writeValueAsString(
                linkedMapOf(
                    "eventId" to eventId.toString(),
                    "eventType" to eventType,
                    "schemaVersion" to schemaVersion,
                    "tenantId" to tenantId,
                    "aggregateType" to aggregateType,
                    "aggregateId" to aggregateId,
                    "aggregateVersion" to aggregateVersion,
                    "payload" to payload,
                    "payloadDigest" to payloadDigest,
                    "occurredAt" to occurredAt.toString(),
                    "recordedAt" to recordedAt.toString(),
                ),
            )

    /**
     * wirePayloadDigest은 사용량 계량·청구 요청의 인증·권한·무결성을 확인하고, 실패 시 민감한 내부 상태를 노출하지 않은 채 업무 처리를 차단합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    fun wirePayloadDigest(): String = digestOf(wirePayload())

    companion object: KLogging() {
        /**
         * `serialVersionUID`은 사용량 과금·정산에서 Java 직렬화 호환성을 유지하는 기술 메타데이터입니다.
         *
         * 도메인 상태가 아니므로 값을 바꾸거나 업무 식별자로 사용하지 않습니다.
         */
        private const val serialVersionUID: Long = 1L

        /**
         * create은 사용량 계량·청구 업무 명령을 접수해 입력을 검증하고, 저장소의 확정 상태와 후속 이벤트가 같은 revision을 가리키도록 처리합니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param eventId 처리할 사용량 계량·청구 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
         * @param eventType 사용량 계량·청구 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
         * @param schemaVersion 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
         * @param tenantId 사용량 계량·청구 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
         * @param aggregateId 처리할 사용량 계량·청구 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
         * @param aggregateVersion 낙관적 동시성 또는 이벤트 순서를 확인하는 기대값입니다. 불일치하면 오래된 명령으로 처리합니다.
         * @param payload 사용량 계량·청구 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
         * @param occurredAt 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
         * @param recordedAt 사용량 계량·청구 상태 변경을 나타내는 이벤트 또는 저장 레코드입니다. 순서·revision·중복 여부를 보존해야 합니다.
         */
        fun create(
            eventId: UUID,
            eventType: String,
            schemaVersion: Int,
            tenantId: String,
            aggregateId: String,
            aggregateVersion: Long,
            payload: String,
            occurredAt: Instant,
            recordedAt: Instant,
        ): BillingIntegrationEnvelope =
            BillingIntegrationEnvelope(
                eventId = eventId,
                eventType = eventType,
                schemaVersion = schemaVersion,
                tenantId = tenantId,
                aggregateType = "BillingPeriod",
                aggregateId = aggregateId,
                aggregateVersion = aggregateVersion,
                payload = payload,
                payloadDigest = digestOf(payload),
                occurredAt = occurredAt,
                recordedAt = recordedAt,
            )

        /**
         * digestOf은 사용량 계량·청구 요청의 인증·권한·무결성을 확인하고, 실패 시 민감한 내부 상태를 노출하지 않은 채 업무 처리를 차단합니다.
         *
         * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
         *
         * @param payload 사용량 계량·청구 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
         */
        private fun digestOf(payload: String): String =
            PayloadDigest.of(payload)
    }
}

/**
 * BillingEnvelopeCodecRegistry은 사용량 과금 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에
 * 맞춰 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
class BillingEnvelopeCodecRegistry {
    /**
     * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val supportedSchemas: Set<BillingEnvelopeSchema> = setOf(
        BillingEnvelopeSchema("ChargeRated", 1),
        BillingEnvelopeSchema("AdjustmentPosted", 1),
        BillingEnvelopeSchema("BillingPeriodClosed", 1),
    )

    /**
     * validate은 사용량 계량·청구 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param envelope 사용량 계량·청구 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     */
    fun validate(envelope: BillingIntegrationEnvelope): BillingIntegrationEnvelope {
        if (!envelope.hasValidPayloadDigest()) throw InvalidBillingEnvelopeDigest(envelope.eventId)

        if (BillingEnvelopeSchema(envelope.eventType, envelope.schemaVersion) !in supportedSchemas) {
            throw UnsupportedBillingEnvelopeVersion(envelope.eventType, envelope.schemaVersion)
        }
        return envelope
    }
}
/**
 * BillingEnvelopeSchema은 사용량 계량·청구에서 전달되는 불변 데이터 모델입니다.
 * @property eventType 사용량 계량·청구 경계에서 전달되는 업무 내용입니다. 스키마·크기·무결성을 검증한 뒤 저장·발행하며 후속 상태 전이에 필요한 정보만
 * 포함합니다.
 * @property schemaVersion 동시성 제어와 이벤트 재생 순서를 나타내는 버전 값입니다. 기대값과 비교해 오래된 명령·중복 이벤트를 거부합니다.
 */


data class BillingEnvelopeSchema(
    /**
     * `eventType`은 사용량 과금·정산에서 응답·재시도·보상·운영 분기를 선택하는 안정된 업무 코드입니다.
     *
     * 저장값과 외부 응답에서 의미를 바꾸지 말고 호출자가 처리할 수 있는 계약으로 유지합니다.
     */
    val eventType: String,
    /**
     * `schemaVersion`은 사용량 과금·정산에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    val schemaVersion: Int,
): Serializable {
    private companion object {
        /**
         * `serialVersionUID`은 사용량 과금·정산에서 Java 직렬화 호환성을 유지하는 기술 메타데이터입니다.
         *
         * 도메인 상태가 아니므로 값을 바꾸거나 업무 식별자로 사용하지 않습니다.
         */
        private const val serialVersionUID: Long = 1L
    }
}

/**
 * UnsupportedBillingEnvelopeVersion은 사용량 과금 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의
 * 규칙에 맞춰 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
class UnsupportedBillingEnvelopeVersion(
    eventType: String,
    schemaVersion: Int,
): IllegalArgumentException("unsupported_billing_envelope:$eventType:$schemaVersion")

/**
 * InvalidBillingEnvelopeDigest은 사용량 과금 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에
 * 맞춰 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
class InvalidBillingEnvelopeDigest(eventId: UUID): IllegalArgumentException("invalid_billing_envelope_digest:$eventId")
