package io.bluetape4k.workshop.commerce.metering.config

import io.bluetape4k.javatimes.days
import io.bluetape4k.javatimes.hours
import io.bluetape4k.javatimes.minutes
import io.bluetape4k.javatimes.requirePositiveDuration
import io.bluetape4k.javatimes.seconds
import io.bluetape4k.logging.KLogging
import io.bluetape4k.support.requireGt
import io.bluetape4k.support.requireInRange
import org.springframework.boot.context.properties.ConfigurationProperties
import java.time.Duration
/**
 * MeteringProperties은 사용량 계량·청구에서 전달되는 불변 데이터 모델입니다.
 * @property commandReceipt 사용량 계량·청구 경계에서 전달되는 업무 내용입니다. 스키마·크기·무결성을 검증한 뒤 저장·발행하며 후속 상태 전이에 필요한
 * 정보만 포함합니다.
 * @property allowedLateness 사용량 계량·청구 정책을 켜고 끄는 플래그입니다. true/false 각각의 처리 경로와 기본값을 계약으로 유지해야 합니다.
 * @property occurredAtRetention 재시도·임대·보존·처리 제한을 결정하는 시간 길이입니다. 장애 시 무한 대기나 중복 실행을 막는 정책 경계입니다.
 * @property occurredAtFutureSkew 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property close 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property reconciliation 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property schemaInitializerEnabled 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야
 * 합니다.
 * @property demoEnabled 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


@ConfigurationProperties("workshop.metering")
data class MeteringProperties(
    /**
     * `commandReceipt`은 사용량 과금·정산에서 서비스 경계와 교환하는 내구성 메시지 또는 업무 사실입니다.
     *
     * at-least-once 전달과 중복·순서 뒤바뀜을 고려해 digest·idempotency·quarantine 규칙을 적용합니다.
     */
    val commandReceipt: CommandReceipt = CommandReceipt(),
    /**
     * `allowedLateness`은 사용량 과금·정산에서 업무 규칙의 허용 여부를 나타내는 flag입니다.
     *
     * true와 false 각각의 분기를 명시적으로 처리하고 기본값이 안전한 거부인지 확인합니다.
     */
    val allowedLateness: Duration = DEFAULT_ALLOWED_LATENESS,
    /**
     * `occurredAtRetention`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val occurredAtRetention: Duration = DEFAULT_OCCURRED_AT_RETENTION,
    /**
     * `occurredAtFutureSkew`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val occurredAtFutureSkew: Duration = DEFAULT_FUTURE_SKEW,
    /**
     * `close`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val close: Close = Close(),
    /**
     * `reconciliation`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    val reconciliation: Reconciliation = Reconciliation(),
    /**
     * `schemaInitializerEnabled`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val schemaInitializerEnabled: Boolean = false,
    /**
     * `demoEnabled`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val demoEnabled: Boolean = false,
) {

    companion object: KLogging() {
        /**
         * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val DEFAULT_ALLOWED_LATENESS: Duration = 48.hours()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        val DEFAULT_OCCURRED_AT_RETENTION: Duration = 400.days()
        /**
         * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        val DEFAULT_FUTURE_SKEW: Duration = 5.minutes()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        val DEFAULT_RECEIPT_LEASE: Duration = 30.seconds()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        val DEFAULT_RECEIPT_RETENTION: Duration = 24.hours()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        val DEFAULT_SCHEDULER_DELAY: Duration = 5.seconds()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        private val MIN_RECEIPT_LEASE: Duration = 5.seconds()
        /**
         * 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
         */
        private val MAX_RECEIPT_LEASE: Duration = 5.minutes()
        /**
         * `MAX_TERMINAL_RESPONSE_BYTES`은 사용량 과금·정산에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
         *
         * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
         */
        const val MAX_TERMINAL_RESPONSE_BYTES: Int = 16 * 1024
        /**
         * `MAX_CLOSE_BATCH_SIZE`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        const val MAX_CLOSE_BATCH_SIZE: Int = 1_000
        /**
         * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
         */
        const val MAX_BATCHES_PER_TICK: Int = 20
        /**
         * `MAX_RECONCILIATION_PAGE_SIZE`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        const val MAX_RECONCILIATION_PAGE_SIZE: Int = 500
    }

    init {
        allowedLateness.requirePositiveDuration("allowedLateness")
        occurredAtRetention.requirePositiveDuration("occurredAtRetention")
        occurredAtFutureSkew.compareTo(Duration.ZERO)
            .requireInRange(0, Int.MAX_VALUE, "occurredAtFutureSkew.compareTo(Duration.ZERO)")
    }
/**
 * CommandReceipt은 사용량 계량·청구에서 전달되는 불변 데이터 모델입니다.
 * @property lease 재시도·임대·보존·처리 제한을 결정하는 시간 길이입니다. 장애 시 무한 대기나 중복 실행을 막는 정책 경계입니다.
 * @property retention 재시도·임대·보존·처리 제한을 결정하는 시간 길이입니다. 장애 시 무한 대기나 중복 실행을 막는 정책 경계입니다.
 * @property terminalResponseBytes 동시 처리량·할당량·집계 수량 또는 처리 진척도입니다. 음수·한도 초과를 검증하고 경쟁 요청에서도 원자적으로
 * 갱신해야 합니다.
 */


    data class CommandReceipt(
        /**
         * `lease`은 사용량 과금·정산에서 멱등성·무결성·lease fencing을 확인하는 보호 값입니다.
         *
         * 원문 비밀값을 로그·일반 응답에 노출하지 않고 재시도와 오래된 worker를 안전하게 차단합니다.
         */
        val lease: Duration = DEFAULT_RECEIPT_LEASE,
        /**
         * `retention`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val retention: Duration = DEFAULT_RECEIPT_RETENTION,
        /**
         * `terminalResponseBytes`은 사용량 과금·정산에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
         *
         * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
         */
        val terminalResponseBytes: Int = MAX_TERMINAL_RESPONSE_BYTES,
    ) {
        init {
            lease.requireInRange(MIN_RECEIPT_LEASE, MAX_RECEIPT_LEASE, "lease")
            retention.requireGt(lease, "retention")
            terminalResponseBytes.requireInRange(1, MAX_TERMINAL_RESPONSE_BYTES, "terminalResponseBytes")
        }
    }
/**
 * Close은 사용량 계량·청구에서 전달되는 불변 데이터 모델입니다.
 * @property batchSize 동시 처리량·할당량·집계 수량 또는 처리 진척도입니다. 음수·한도 초과를 검증하고 경쟁 요청에서도 원자적으로 갱신해야 합니다.
 * @property maxBatchSize 동시 처리량·할당량·집계 수량 또는 처리 진척도입니다. 음수·한도 초과를 검증하고 경쟁 요청에서도 원자적으로 갱신해야 합니다.
 * @property maxBatchesPerTick 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 * @property schedulerDelay 재시도·임대·보존·처리 제한을 결정하는 시간 길이입니다. 장애 시 무한 대기나 중복 실행을 막는 정책 경계입니다.
 * @property schedulerEnabled 사용량 계량·청구 업무 흐름을 구성하는 값입니다. 명령 검증과 영속화·이벤트 변환 시 이 값의 의미를 보존해야 합니다.
 */


    data class Close(
        /**
         * `batchSize`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        val batchSize: Int = 200,
        /**
         * `maxBatchSize`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        val maxBatchSize: Int = 1_000,
        /**
         * `maxBatchesPerTick`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
         *
         * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
         */
        val maxBatchesPerTick: Int = 5,
        /**
         * `schedulerDelay`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val schedulerDelay: Duration = DEFAULT_SCHEDULER_DELAY,
        /**
         * `schedulerEnabled`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val schedulerEnabled: Boolean = true,
    ) {
        init {
            maxBatchSize.requireInRange(1, MAX_CLOSE_BATCH_SIZE, "maxBatchSize")
            batchSize.requireInRange(1, maxBatchSize, "batchSize")
            maxBatchesPerTick.requireInRange(1, MAX_BATCHES_PER_TICK, "maxBatchesPerTick")
            schedulerDelay.requirePositiveDuration("schedulerDelay")
        }
    }
/**
 * Reconciliation은 사용량 계량·청구에서 전달되는 불변 데이터 모델입니다.
 * @property pageSize 동시 처리량·할당량·집계 수량 또는 처리 진척도입니다. 음수·한도 초과를 검증하고 경쟁 요청에서도 원자적으로 갱신해야 합니다.
 * @property maxPageSize 동시 처리량·할당량·집계 수량 또는 처리 진척도입니다. 음수·한도 초과를 검증하고 경쟁 요청에서도 원자적으로 갱신해야 합니다.
 */


    data class Reconciliation(
        /**
         * `pageSize`은 사용량 과금·정산에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
         *
         * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
         */
        val pageSize: Int = 200,
        /**
         * `maxPageSize`은 사용량 과금·정산에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
         *
         * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
         */
        val maxPageSize: Int = 500,
    ) {
        init {
            maxPageSize.requireInRange(1, MAX_RECONCILIATION_PAGE_SIZE, "maxPageSize")
            pageSize.requireInRange(1, maxPageSize, "pageSize")
        }
    }
}
