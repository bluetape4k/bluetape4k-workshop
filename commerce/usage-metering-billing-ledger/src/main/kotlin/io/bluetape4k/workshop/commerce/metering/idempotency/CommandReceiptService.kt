    companion object: KLogging()

    /**
     * acquire은 사용량 계량·청구의 동시 작업에서 한 실행자만 처리하도록 lease·lock을 원자적으로 획득·갱신하고 만료·소유자 불일치를 거절합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param scope 업무 처리에 필요한 scope 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param requestFingerprint 사용량 계량·청구 명령의 입력입니다. 스키마·필수값·중복 키를 검증한 뒤 부작용을 시작합니다.
     * @param ownerToken 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     */
    @Transactional(propagation = Propagation.REQUIRES_NEW)
    @Suppress("ReturnCount") // Each branch is a distinct receipt state-machine transition.
    fun acquire(
        scope: CommandReceiptScope,
        requestFingerprint: Sha256Digest,
        ownerToken: UUID = Uuid.V7.nextId(),
    ): CommandAcquireResult {
        /**
         * `now`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val now = clock.instant()
        /**
         * `receiptProperties`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val receiptProperties = properties.commandReceipt
        /**
         * `inserted`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val inserted = repository.insertOwnerIfAbsent(
            CommandReceiptOwnerInsert(
                scope = scope,
                requestFingerprint = requestFingerprint.value,
                ownerToken = ownerToken,
                now = now,
                leaseDeadline = now.plus(receiptProperties.lease),
                retentionDeadline = now.plus(receiptProperties.retention),
            )
        )
        /**
         * `current`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        var current = repository.find(scope) ?: error("command receipt was not persisted")
        if (inserted) return CommandAcquireResult.Acquired(current, takeover = false)
        if (current.requestFingerprint != requestFingerprint.value) return CommandAcquireResult.Conflict
        if (current.status != CommandReceiptStatus.IN_PROGRESS) {
            return CommandAcquireResult.Replay(
                httpStatus = requireNotNull(current.terminalHttpStatus),
                response = requireNotNull(current.terminalResponse),
                failed = current.status == CommandReceiptStatus.FAILED,
            )
        }
        if (current.leaseDeadline > now) {
            return CommandAcquireResult.InProgress(Duration.between(now, current.leaseDeadline))
        }

        /**
         * `taken`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val taken = repository.takeover(
            current = current,
            ownerToken = ownerToken,
            now = now,
            leaseDeadline = now.plus(receiptProperties.lease),
            retentionDeadline = now.plus(receiptProperties.retention),
        )
        current = repository.find(scope) ?: error("command receipt disappeared during takeover")

        return if (taken) {
            CommandAcquireResult.Acquired(current, takeover = true)
        } else {
            CommandAcquireResult.InProgress(Duration.between(now, current.leaseDeadline).coerceAtLeast(Duration.ZERO))
        }
    }

    /**
     * succeed은 사용량 계량·청구의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param receiptId 처리할 사용량 계량·청구 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param ownerToken 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     * @param httpStatus 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param response 업무 처리에 필요한 response 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    @Transactional
    fun succeed(receiptId: UUID, ownerToken: UUID, httpStatus: Int, response: String): Boolean =
        complete(
            receiptId = receiptId,
            ownerToken = ownerToken,
            status = CommandReceiptStatus.SUCCEEDED,
            httpStatus = httpStatus,
            response = response
        )

    /**
     * fail은 사용량 계량·청구의 업무 규칙을 한 곳에서 적용하여 검증·상태 전이·영속화 결과가 서로 어긋나지 않도록 합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param receiptId 처리할 사용량 계량·청구 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param ownerToken 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     * @param httpStatus 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param response 업무 처리에 필요한 response 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    @Transactional
    fun fail(receiptId: UUID, ownerToken: UUID, httpStatus: Int, response: String): Boolean =
        complete(
            receiptId = receiptId,
            ownerToken = ownerToken,
            status = CommandReceiptStatus.FAILED,
            httpStatus = httpStatus,
            response = response
        )

    /**
     * complete은 사용량 계량·청구의 재고·할당량·금액을 검증한 뒤 한 번만 상태 전이시키고, 충돌·재시도·보상 결과를 감사 가능한 형태로 남깁니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param receiptId 처리할 사용량 계량·청구 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param ownerToken 명령을 수행한 주체 또는 lease 소유자입니다. 권한·감사·동시성 검증에 사용합니다.
     * @param status 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param httpStatus 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param response 업무 처리에 필요한 response 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private fun complete(
        receiptId: UUID,
        ownerToken: UUID,
        status: CommandReceiptStatus,
        httpStatus: Int,
        response: String,
    ): Boolean {
        response.toUtf8Bytes().size.requireInRange(
            0,
            properties.commandReceipt.terminalResponseBytes,
            "terminalResponse.bytes",
        )
        httpStatus.requireInRange(MIN_HTTP_STATUS, MAX_HTTP_STATUS, "httpStatus")

        val now = clock.instant()
        return repository.complete(
            CommandReceiptCompletion(
                receiptId = receiptId,
                ownerToken = ownerToken,
                status = status,
                httpStatus = httpStatus,
                response = response,
                now = now,
                retentionDeadline = now + properties.commandReceipt.retention,
            )
        )
    }

    /**
     * cleanupExpiredTerminal은 사용량 계량·청구의 취소·보상·종료 전이를 허용된 terminal 규칙에 따라 적용하고, 이미 처리된 요청은 멱등하게
     * 유지합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param limit 한 번에 처리할 상한입니다. backpressure와 운영 자원 한도를 넘지 않도록 적용합니다.
     */
    @Transactional
    fun cleanupExpiredTerminal(limit: Int = DEFAULT_CLEANUP_BATCH_SIZE): Int {
        limit.requireInRange(1, MAX_CLEANUP_BATCH_SIZE, "limit")

        return repository.deleteExpiredTerminalBatch(clock.instant(), limit)
    }
