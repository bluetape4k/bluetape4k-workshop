package io.bluetape4k.workshop.commerce.metering.persistence

import io.bluetape4k.concurrent.tryAcquire
import io.bluetape4k.javatimes.millis
import io.bluetape4k.javatimes.requirePositiveDuration
import io.bluetape4k.support.requirePositiveNumber
import org.jetbrains.exposed.v1.core.DatabaseConfig
import org.jetbrains.exposed.v1.jdbc.Database
import org.jetbrains.exposed.v1.jdbc.JdbcTransaction
import org.jetbrains.exposed.v1.jdbc.transactions.TransactionManager
import org.jetbrains.exposed.v1.jdbc.transactions.transaction
import java.time.Duration
import java.util.concurrent.Semaphore
import java.util.concurrent.atomic.AtomicBoolean
import javax.sql.DataSource
import kotlin.time.toKotlinDuration

/**
 * `DEFAULT_PERMIT_TIMEOUT_MILLIS`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
 *
 * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
 */
private const val DEFAULT_PERMIT_TIMEOUT_MILLIS = 250L
/**
 * `DEFAULT_PERMIT_TIMEOUT`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
 *
 * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
 */
private val DEFAULT_PERMIT_TIMEOUT: Duration = DEFAULT_PERMIT_TIMEOUT_MILLIS.millis()

/**
 * MeteringDatabasePermitUnavailable은 사용량 과금 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의
 * 규칙에 맞춰 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
class MeteringDatabasePermitUnavailable: IllegalStateException("metering_database_permit_unavailable")

/**
 * MeteringJdbcTransaction은 사용량 과금 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
 * 해석합니다.
 *
 * 이 설명은 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이의 업무 계약을 함께 이해하기 위한 것입니다.
 */
class MeteringJdbcTransaction internal constructor(
    /**
     * `exposed`은 사용량 과금·정산에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    val exposed: JdbcTransaction,
) {
    /**
     * withExposed은 사용량 계량·청구 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param block 업무 처리에 필요한 block 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    inline fun <T> withExposed(block: JdbcTransaction.() -> T): T = exposed.block()
}
/**
 * MeteringJdbcExecutor은 사용량 계량·청구에서 사용하는 업무 객체입니다.
 * @property permitTimeout 재시도·임대·보존·처리 제한을 결정하는 시간 정책입니다. 장애 시 무한 대기와 중복 실행을 막습니다.
 */


class MeteringJdbcExecutor(
    dataSource: DataSource,
    foregroundPermits: Int = 8,
    /**
     * `permitTimeout`은 사용량 과금·정산에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val permitTimeout: Duration = DEFAULT_PERMIT_TIMEOUT,
): AutoCloseable {
    /**
     * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val permits = Semaphore(foregroundPermits, true)
    /**
     * 사용량 계량·청구 클래스가 유지하는 업무 상태입니다. 변경 시 관련 검증·상태 전이·동시성 규칙을 함께 적용합니다.
     */
    private val closed = AtomicBoolean()
    /**
     * 사용량 계량·청구 경계의 전달 데이터입니다. 스키마·크기·무결성을 검증한 뒤 저장하거나 발행합니다.
     */
    private val database = Database.connect(
        datasource = dataSource,
        databaseConfig = DatabaseConfig { defaultMaxAttempts = 1 },
    )

    init {
        foregroundPermits.requirePositiveNumber("foregroundPermits")
        permitTimeout.requirePositiveDuration("permitTimeout")
    }

    /**
     * transaction은 사용량 계량·청구 저장소를 transaction 경계 안에서 변경하며 idempotency key·revision·감사 필드를 함께 보존합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param block 업무 처리에 필요한 block 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    fun <T> transaction(block: MeteringJdbcTransaction.() -> T): T {
        check(!closed.get()) { "metering_jdbc_executor_closed" }
        if (!permits.tryAcquire(permitTimeout.toKotlinDuration())) {
            throw MeteringDatabasePermitUnavailable()
        }
        try {
            return transaction(database) {
                MeteringJdbcTransaction(this).block()
            }
        } finally {
            permits.release()
        }
    }

    /**
     * close은 사용량 계량·청구의 취소·보상·종료 전이를 허용된 terminal 규칙에 따라 적용하고, 이미 처리된 요청은 멱등하게 유지합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    override fun close() {
        if (closed.compareAndSet(false, true)) {
            TransactionManager.closeAndUnregister(database)
        }
    }
}
