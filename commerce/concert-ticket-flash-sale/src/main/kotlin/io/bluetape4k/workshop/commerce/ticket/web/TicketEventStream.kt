/** snapshot-first bounded broadcaster입니다. client가 연결된 동안 JDBC resource를 보유하지 않습니다. */
class TicketEventStream(
    /**
     * `queueSize`은 콘서트 티켓 플래시 세일에서 한도·할당·정산·처리 진척을 계산하는 업무 수치입니다.
     *
     * 음수·상한·단위와 반올림 규칙을 검증하고 경쟁 요청에서도 원자적으로 갱신합니다.
     */
    private val queueSize: Int,
    maxConnections: Int,
    /**
     * `retainedEvents`은 콘서트 티켓 플래시 세일에서 서비스 경계와 교환하는 내구성 메시지 또는 업무 사실입니다.
     *
     * at-least-once 전달과 중복·순서 뒤바뀜을 고려해 digest·idempotency·quarantine 규칙을 적용합니다.
     */
    private val retainedEvents: Int = 1_024,
    /**
     * `clock`은 콘서트 티켓 플래시 세일에서 만료·재시도·SLA·정산 경계를 계산하는 업무 시각 또는 기간입니다.
     *
     * clock과 timezone 정책을 고정하고 저장·이벤트·응답에서 같은 기준으로 해석합니다.
     */
    private val clock: Clock = Clock.systemUTC(),
): AutoCloseable {

    companion object: KLogging() {
        /**
         * `SENSITIVE_FIELDS`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        private val SENSITIVE_FIELDS = setOf(
            "buyerSubjectId",
            "ipSubjectId",
            "authorizationOperationId",
            "refundOperationId",
            "paymentOutcome",
        )
    }

    /**
     * `lock`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val lock = ReentrantLock()
    /**
     * `sequence`은 콘서트 티켓 플래시 세일에서 낙관적 동시성과 이벤트·메시지 재생 순서를 검증하는 버전 값입니다.
     *
     * 기대값과 비교해 오래된 명령·중복 이벤트·잘못된 재생을 거절합니다.
     */
    private val sequence = AtomicLong()
    /**
     * `permits`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val permits = Semaphore(maxConnections, true)
    /**
     * `retained`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val retained = ArrayDeque<ScopedEvent>()
    /**
     * `subscriptions`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val subscriptions = linkedSetOf<TicketSubscription>()
    /**
     * `accepting`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val accepting = AtomicBoolean(true)

    init {
        queueSize.requirePositiveNumber("queueSize")
        maxConnections.requirePositiveNumber("maxConnections")
        retainedEvents.requireGe(queueSize, "retainedEvents")
    }

    /**
     * publish은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     * @param scope 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     * @param type 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     * @param payload 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     */
    fun publish(scope: StreamScope, type: String, payload: Map<String, String>): TicketStreamEvent {
        type.requireNotBlank("type")
        payload.keys.none(SENSITIVE_FIELDS::contains).requireBeTrue { "payload keys not in SENSITIVE_FIELDS" }

        lock.withLock {
            val event = TicketStreamEvent(sequence.incrementAndGet(), type, payload.toMap(), clock.instant())
            retained += ScopedEvent(scope, event)
            while (retained.size > retainedEvents) {
                retained.removeFirst()
            }
            subscriptions.filter { it.scope == scope }.forEach { it.offer(event) }
            return event
        }
    }

    /** 단일 lock 아래에서 catch-up 전에 등록해 snapshot-to-subscribe race를 닫습니다. */
    /** 단일 lock 아래에서 catch-up 전에 등록해 snapshot-to-subscribe race를 닫습니다. */
    fun subscribe(scope: StreamScope, snapshot: () -> Map<String, String>): TicketSubscription {
        if (!accepting.get() || !permits.tryAcquire()) throw TicketStreamCapacityExceeded()
        val highWater = lock.withLock { sequence.get() }

        val snapshotPayload = try {
            snapshot().toMap()
        } catch (failure: Exception) {
            permits.release()
            throw failure
        }

        lock.withLock {
            val subscription = TicketSubscription(scope, queueSize, permits) {
                lock.withLock { subscriptions.remove(it) }
            }
            subscriptions += subscription
            subscription.snapshot = TicketStreamSnapshot(snapshotPayload, highWater, clock.instant())

            retained.asSequence()
                .filter { it.scope == scope && it.event.sequence > highWater }
                .forEach { subscription.offer(it.event) }

            return subscription
        }
    }

    /**
     * activeConnections은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun activeConnections(): Int = lock.withLock { subscriptions.size }

    /**
     * stopNewConnections은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun stopNewConnections() {
        accepting.set(false)
    }

    /**
     * close은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    override fun close() {
        accepting.set(false)
        lock.withLock {
            subscriptions.forEach { subscription ->
                subscription.closeSafe()
            }
        }
    }

    /**
     * ScopedEvent은 콘서트 티켓 플래시 세일 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
     * 해석합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    private data class ScopedEvent(
        /**
         * `scope`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val scope: StreamScope,
        /**
         * `event`은 콘서트 티켓 플래시 세일에서 서비스 경계와 교환하는 내구성 메시지 또는 업무 사실입니다.
         *
         * at-least-once 전달과 중복·순서 뒤바뀜을 고려해 digest·idempotency·quarantine 규칙을 적용합니다.
         */
        val event: TicketStreamEvent,
    ): Serializable {
        companion object {
            @Serial
            /**
             * `serialVersionUID`은 콘서트 티켓 플래시 세일에서 Java 직렬화 호환성을 유지하는 기술 메타데이터입니다.
             *
             * 도메인 상태가 아니므로 값을 바꾸거나 업무 식별자로 사용하지 않습니다.
             */
            private const val serialVersionUID: Long = 1L
        }
    }
}

/**
 * TicketSubscription은 콘서트 티켓 플래시 세일 실무 예제의 업무 경계를 표현하는 타입입니다. 입력 검증, 상태 전이, 저장·발행 계약을 이 타입의 규칙에 맞춰
 * 해석합니다.
 *
 * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 */
class TicketSubscription internal constructor(
    /**
     * `scope`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    internal val scope: StreamScope,
    queueSize: Int,
    /**
     * `permits`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val permits: Semaphore,
    /**
     * `detach`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val detach: (TicketSubscription) -> Unit,
): AutoCloseable {

    companion object: KLogging()

    /**
     * `queue`은 콘서트 티켓 플래시 세일에서 저장 객체·외부 리소스·전송 경계를 가리키는 참조 값입니다.
     *
     * allowlist·sanitize·소유권 검사를 거친 뒤 API·저장소·이벤트에서 동일한 key 규칙을 사용합니다.
     */
    private val queue = ArrayBlockingQueue<TicketStreamEvent>(queueSize)
    /**
     * `closed`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    private val closed = AtomicBoolean()

    /**
     * `snapshot`은 콘서트 티켓 플래시 세일에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
     *
     * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
     */
    lateinit var snapshot: TicketStreamSnapshot
        internal set

    /**
     * offer은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     * @param event 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     */
    internal fun offer(event: TicketStreamEvent) {
        if (!closed.get() && !queue.offer(event)) {
            close()
            throw TicketStreamSlowConsumer()
        }
    }

    /**
     * poll은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun poll(): TicketStreamEvent? = queue.poll()

    /**
     * close은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    override fun close() {
        if (closed.compareAndSet(false, true)) {
            detach(this)
            permits.release()
        }
    }
}
