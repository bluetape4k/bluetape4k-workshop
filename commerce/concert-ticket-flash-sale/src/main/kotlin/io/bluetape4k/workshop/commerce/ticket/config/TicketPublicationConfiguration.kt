        TicketJdbcExecutor(
            dataSource = dataSource,
            foregroundPermits = properties.db.foregroundPermits,
            permitTimeout = properties.db.permitTimeout,
        )

    @Bean
    /**
     * ticketSaleService은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun ticketSaleService(): SaleService = SaleService()

    @Bean
    /**
     * ticketAdmissionService은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     * @param jdbc 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     * @param clock 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     */
    fun ticketAdmissionService(jdbc: TicketJdbcExecutor, clock: Clock): AdmissionService = AdmissionService(jdbc, clock)

    @Bean
    /**
     * purchaseEventPublisher은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     * @param events 업무 입력입니다. 필수값·권한·멱등성 범위를 검증한 뒤 부작용을 시작합니다.
     */
    fun purchaseEventPublisher(events: ApplicationEventPublisher): PurchaseEventPublisher =
        PurchaseEventPublisher(events::publishEvent)

    @Bean
    /**
     * purchaseService은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun purchaseService(
        jdbc: TicketJdbcExecutor,
        sale: SaleService,
        admission: AdmissionService,
        clock: Clock,
        events: PurchaseEventPublisher,
    ): PurchaseService = PurchaseService(jdbc, sale, admission, clock, events)

    @Bean
    /**
     * paymentProvider은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
     * 호출자는 저장소의 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     */
    fun paymentProvider(): FakePaymentProvider = FakePaymentProvider()

    @Bean
    /**
     * paymentWorker은 콘서트 티켓 플래시 세일 업무 규칙을 적용해 입력 검증, 상태 전이, 영속화 및 후속 이벤트 처리의 일관성을 보장합니다.
     *
