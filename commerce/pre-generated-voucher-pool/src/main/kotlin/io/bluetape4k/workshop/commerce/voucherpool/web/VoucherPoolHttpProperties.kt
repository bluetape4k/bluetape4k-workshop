 * requireBoundedUtf8은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분 저장을 막습니다.
 *
 * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
 *
 * @param value 업무 처리에 필요한 value 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
 * @param maxBytes 한 번에 처리할 상한입니다. backpressure와 운영 자원 한도를 넘지 않도록 적용합니다.
 */
internal fun requireBoundedUtf8(value: String, maxBytes: Int): String {
    if (value.toUtf8Bytes().size > maxBytes || value.any(Character::isISOControl)) {
        throw invalidRequest()
    }
    return value
}

