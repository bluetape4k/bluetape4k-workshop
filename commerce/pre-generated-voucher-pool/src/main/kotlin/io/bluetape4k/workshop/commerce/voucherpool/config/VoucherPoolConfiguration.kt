     * @param transactionManager 업무 처리에 필요한 transactionManager 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param metrics 업무 처리에 필요한 metrics 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     * @param lockTimeoutApplier 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     * @param timeouts 업무 판정에 사용하는 기준 시각입니다. 테스트·재시도에서도 동일한 시간 규칙을 적용합니다.
     */
    @Bean
    fun voucherPoolJdbcExecutor(
        gate: DatabasePermitGate,
        @Qualifier("springTransactionManager") transactionManager: PlatformTransactionManager,
        metrics: VoucherPoolJdbcMetrics,
        lockTimeoutApplier: VoucherPoolLockTimeoutApplier,
        timeouts: VoucherPoolJdbcTimeouts,
    ): VoucherPoolJdbcExecutor =
        VoucherPoolJdbcExecutor(
            gate = gate,
            transactionManager = transactionManager,
            timeouts = timeouts,
            metrics = metrics,
            lockTimeoutApplier = lockTimeoutApplier,
        )

    /**
     * toPermitConfig은 프로모션 바우처 실행에 필요한 구성과 운영 수치를 제공하며, 잘못된 값이 실제 업무 처리 전에 드러나도록 합니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    private fun VoucherPoolLaneProperties.toPermitConfig(): PermitLaneConfig =
        PermitLaneConfig(
            capacity = capacity,
            wait = permitWait.toKotlinDuration(),
        )

    /**
     * requireHikariDataSource은 프로모션 바우처 명령의 불변조건과 tenant·revision 범위를 부작용 전에 검증하여 잘못된 상태 전이와 부분
     * 저장을 막습니다.
     *
     * 호출 결과는 업무 상태와 감사·재시도 규칙을 보존한 뒤 다음 계층으로 전달해야 합니다.
     */
    private fun DataSource.requireHikariDataSource(): HikariDataSource =
        this as? HikariDataSource
            ?: error(
                "pre-generated-voucher-pool requires HikariDataSource " +
                        "so the live pool size and connection timeout remain authoritative",
            )
}
