     * @param limit 한 번에 처리할 상한입니다. backpressure와 운영 자원 한도를 넘지 않도록 적용합니다.
     */
    override fun stuckReservations(
        tenantId: String,
        campaignId: UUID?,
        cursor: StuckReservationCursor?,
        limit: Int,
