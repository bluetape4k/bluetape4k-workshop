        return executor.operatorTransaction {
            if (!store.scopeExists(tenantId, campaignId, null)) return@operatorTransaction null
            store.findStuckReservations(tenantId, campaignId, cursor, limit)
        }
    }

    /**
     * withUserDigest은 프로모션 바우처 요청의 인증·권한·무결성을 확인하고, 실패 시 민감한 내부 상태를 노출하지 않은 채 업무 처리를 차단합니다.
     *
     * 호출자는 저장소 확정 상태와 이벤트 결과를 확인한 뒤 다음 업무 단계를 진행해야 합니다.
     *
     * @param tenantId 프로모션 바우처 경계를 식별하는 값이며 다른 tenant 데이터와 섞이지 않도록 조회·변경 범위를 제한합니다.
     * @param campaignId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param principalId 처리할 프로모션 바우처 업무 객체의 식별자입니다. 존재 여부와 호출자의 접근 범위를 함께 확인합니다.
     * @param block 업무 처리에 필요한 block 값이며 관련 불변조건과 저장·이벤트 계약을 함께 만족해야 합니다.
     */
    private inline fun <T> withUserDigest(
        tenantId: String,
        campaignId: UUID,
        principalId: String,
        block: (ByteArray) -> T,
    ): T {
        val keyVersion = checkNotNull(store.findUserIdentityKeyVersion(tenantId, campaignId))
        val digest = digests.userIdentity(tenantId, campaignId, principalId, keyVersion).copyBytes()

        return try {
            block(digest)
        } finally {
            digest.fill(0)
        }
    }
}

