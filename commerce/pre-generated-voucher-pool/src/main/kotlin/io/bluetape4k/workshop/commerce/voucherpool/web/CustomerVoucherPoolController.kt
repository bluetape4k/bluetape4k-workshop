     * 매핑 경계: `GetMapping`. 인증 실패·검증 실패·멱등성 충돌은 성공 응답처럼 숨기지 않고 계약된 오류로 반환합니다.
     * 예:
     * ```kotlin
     * val response = events(principal = principal, cursor = null, lastEventId = "demo", response =
     * response)
     * ```
     * @param principal 요청 경계에서 검증된 `principal`입니다.
     * @param cursor 요청 경계에서 검증된 `cursor`입니다.
     * @param lastEventId 요청 경계에서 검증된 `lastEventId`입니다.
     * @param response 요청 경계에서 검증된 `response`입니다.
     * @return 성공 시 확정된 결과를, 실패 시 호출자가 분기할 수 있는 오류 계약을 반환합니다.
     */
    @GetMapping("/events", produces = [MediaType.TEXT_EVENT_STREAM_VALUE])
    fun events(
        principal: TenantPrincipal,
        @RequestParam(required = false) cursor: String?,
        @RequestHeader("Last-Event-ID", required = false) lastEventId: String?,
        response: HttpServletResponse,
    ) {
        /**
         * `subscription`은 바우처·프로모션에서 업무 흐름을 구성하는 입력 또는 결과 값입니다.
         *
         * 입력 검증, 권한·멱등성, 상태 전이, 영속화와 이벤트 발행 사이에서 이 의미를 보존합니다.
         */
        val subscription = streams.openCustomer(
            tenantId = principal.tenantId,
            principalId = principal.principalId,
            cursor = resolveEventCursor(cursor, lastEventId),
        )
        response.contentType = MediaType.TEXT_EVENT_STREAM_VALUE
        streams.write(subscription, response.outputStream)
    }
}

